#!/usr/bin/env python3
"""The annular bend reference: builds every figure that LIM-021 and this package's README state, and checks them.

    python3 -I -B generators/annular_reference.py           check (the default), from the package directory
    python3 -I -B generators/annular_reference.py --write   rewrite compliance.json, figures.json, the README's
                                                            generated block and SHA256SUMS

Needs numpy and scipy (requirements.txt). Reads, besides this package: the invented benchmark model documents
MODELS_GLOB names (as inputs; never results), and, for the check of the stated figures, LIM-021 in
docs/RELEASE_LIMITATIONS_v1.0.md. It imports no product code.

Tolerance. The check builds everything three times: once as it stands and once for each seed of SEEDS with the
torus's assembled data perturbed by PERTURBATION relative (torus_elasticity.PERTURBATION), a few roundings, as a
different platform's arithmetic would. A figure's sensitivity is the largest change the perturbed builds make in
it; its tolerance is the largest of RTOL relative, ATOL absolute and SAFETY times that sensitivity. This is the
method's own estimate of its roundoff error: the thin-walled sections and the straight limit are ill-conditioned
enough in double precision that a fixed relative tolerance would either hide a real change or fail on a platform.

The check fails, printing what differs, when
- a figure, a physical limit check's observation or a compliance differs from the committed one by more than its
  tolerance (a roundoff residual is checked against its bound only), or any committed value is not of the recomputed type (a count is an integer, exactly);
- a count differs at all, here or in a perturbed build;
- a limit check of any build, or a committed one, is not finite or exceeds its bound (`limits` in figures.json);
- a count's deciding difference lies within MARGIN percentage points of its screen;
- a number the generated block or LIM-021 renders would render differently with its figure moved by its tolerance;
- any field of a compliance.json entry differs (its geometry, material and meshes exactly);
- the README's generated block, rendered from the recomputed figures, differs from the committed block;
- a figure stated in LIM-021 is not the rendering of its keys, or LIM-021 states a number that no key backs;
- the README states a number outside its generated block that is not an identifier;
- the model documents matching MODELS_GLOB are not exactly the ones figures.json records, or one is unread;
- software-workflow.json does not register this check with the rule REQUIRED_PATHS, or the workflow does not run
  it on pull requests touching exactly those paths;
- SHA256SUMS does not list exactly the package's files with their committed bytes.
It writes nothing in check mode; --write refuses to write while any of the first six fails.
"""
