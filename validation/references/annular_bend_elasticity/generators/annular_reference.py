def lmodel(L, R, dt, k, D=1.0):
    """Planar L: two equal legs of length L joined by a bend of L_BEND_ANGLE_DEG and radius R, both ends anchored;
    a uniform rise L_RISE with alpha L_ALPHA and a point force normal to the plane at the bend's far end."""
    t = D / dt
    nodes = [("A", (0, 0, 0)), ("b1", (L, 0, 0)), ("b2", (L + R, R, 0)), ("B", (L + R, L + R, 0))]
    p = [np.array(x, float) for _, x in nodes]
    legs = (p[1] - p[0], p[3] - p[2])
    angle = math.degrees(math.acos(float(legs[0] @ legs[1]) / (np.linalg.norm(legs[0]) * np.linalg.norm(legs[1]))))
    if not math.isclose(angle, L_BEND_ANGLE_DEG) or np.linalg.norm(legs[0]) != np.linalg.norm(legs[1]):
        raise ValueError(f"the L-run's geometry is not two equal legs and a {L_BEND_ANGLE_DEG:g} degree bend")
    sec = {"outside_diameter": {"unit": "m", "value": D}, "wall_thickness": {"unit": "m", "value": t}}
    pipes = [("P1", "A", "b1", (0, 1, 0)), ("BEND", "b1", "b2", (1, -1, 0)), ("P2", "b2", "B", (-1, 0, 0))]
    return {
        "nodes": [{"id": n, "position": dict(zip("xyz", p))} for n, p in nodes],
        "materials": [{"id": "mat", "elastic_modulus": {"unit": "Pa", "value": E},
                       "shear_modulus": {"unit": "Pa", "value": E / 2.6},
                       "thermal_expansion_coefficient": {"unit": "1/degC", "value": L_ALPHA}}],
        "pipe_segments": [{"id": i, "from": a, "to": b, "material": "mat", "section": sec,
                           "y_reference": dict(zip("xyz", y))} for i, a, b, y in pipes],
        "components": [{"kind": "bend", "mechanics_interface": {"solver_consumption": "curved_bend_macro_element"},
                        "geometry": {"bend_pipe_ref": "BEND", "bend_radius": {"unit": "m", "value": R}},
                        "modifiers": {"flexibility_factor_user_value": {"unit": "none", "value": k}}}],
        "supports": [{"id": "sA", "node": "A", "family": "anchor", "restraints": list(fs.DOFS)},
                     {"id": "sB", "node": "B", "family": "anchor", "restraints": list(fs.DOFS)}],
        "load_cases": [
            {"id": "thermal", "primitive_loads": [
                {"category": "thermal", "magnitude": {"unit": "degC", "value": L_RISE}, "target": {"pipe": p}}
                for p in ("P1", "BEND", "P2")]},
            {"id": "outplane", "primitive_loads": [
                {"category": "concentrated_force", "direction": "global_z", "magnitude": {"unit": "N", "value": -1.0e4},
                 "target": {"node": "b2"}}]}]}


def l_reactions(res, case, L):
    """The twelve anchor reaction components of an L-run, moments divided by the leg length."""
    r = res["cases"][case]["reactions"]
    return np.array([r[s][c] / (L if c[0] == "M" else 1.0) for s in ("sA", "sB") for c in fs.FORCES])


def l_measure(qm, qr):
    """L-run measure: the largest componentwise difference over the largest reference component (one scale for
    forces and moments / L), signed by the change in magnitude of the reference's largest component."""
    j = int(np.argmax(np.abs(qr)))
    v = np.max(np.abs(qm - qr)) / np.max(np.abs(qr))
    return math.copysign(v, abs(qm[j]) - abs(qr[j]))


def bench_measure(res_m, res_r):
    """Benchmark measure, per load case: forces and moments each normalized by their own largest reference
    component over every support; the larger of the two, in per cent."""
    out = {}
    for case in res_r["cases"]:
        def vec(res):
            return np.array([[res["cases"][case]["reactions"][sid][k] for k in fs.FORCES]
                             for sid in sorted(res["cases"][case]["reactions"])])
        a, b = vec(res_m), vec(res_r)
        m = 0.0
        for j in (0, 3):
            s = np.max(np.abs(b[:, j:j + 3]))
            if s > 0:
                m = max(m, 100 * np.max(np.abs(a[:, j:j + 3] - b[:, j:j + 3])) / s)
        out[case] = m
    return out


def code_factor(sec, R):
    rm = (sec.ro + sec.ri) / 2
    return max(THIN_SHELL_FLOOR, THIN_SHELL_COEFF * rm * rm / (sec.t * R))


def bench_pairs(mdl, C, sec, R):
    """Per (factor choice, compared model): the (thin arc's error, compared model's error) of each load case of a
    benchmark system, against the same frame with its bends given the elastic compliance C; and the case count.
    The "document" choice leaves each bend its own flexibility_factor_user_value."""
    ref = fs.solve(mdl, straight="timoshenko", compliance=C)
    EI = sec.E * sec.I
    fac = {"fit": (C[5, 5] * EI, C[4, 4] * EI), "code": (code_factor(sec, R),) * 2,
           "unit": (UNIT_FACTOR, UNIT_FACTOR), "oop": (C[4, 4] * EI,) * 2, "document": None}
    out = {}
    for c in CHOICES:
        kw = {} if fac[c] is None else {"k_in": fac[c][0], "k_out": fac[c][1]}
        th = bench_measure(fs.solve(mdl, straight="timoshenko", **kw), ref)
        for mname in MODELS:
            mm = bench_measure(fs.solve(mdl, straight="timoshenko", arc=mname, **kw), ref)
            out[(c, mname)] = [(th[case], mm[case]) for case in th]
    return out, len(ref["cases"])


