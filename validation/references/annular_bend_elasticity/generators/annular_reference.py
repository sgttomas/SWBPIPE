def tally(pairs, tag, margins):
    """(nearer, tied, further, largest gain, largest loss) of (reference model error, compared model error) in
    percentage points; records the smallest distance of a deciding difference from the tie band."""
    d = [abs(t) - abs(m) for t, m in pairs]
    margins[tag] = min(min(abs(x - TIE), abs(x + TIE)) for x in d)
    near = [x for x in d if x > TIE]
    far = [x for x in d if x < -TIE]
    return [len(near), len(d) - len(near) - len(far), len(far)], max(near, default=0.0), -min(far, default=0.0)


def arc_for(R, phi, sec, **kw):
    xi = np.array([R, 0.0, 0.0])
    xj = np.array([R * math.cos(phi), R * math.sin(phi), 0.0])
    mid = 0.5 * (xi + xj)
    yref = mid if np.linalg.norm(mid) > 1e-12 else np.array([0, 1.0, 0])
    if phi > math.pi - 1e-9:
        yref = np.array([0, 1.0, 0])  # semicircle: the chord passes through the centre; bow toward +y
    return fs.Arc(xi, xj, R, yref, sec, **kw)


def tip_local(arc):
    F = arc.tip_flexibility()
    T = np.zeros((6, 6))
    T[:3, :3] = T[3:, 3:] = arc.frame(arc.phi)
    return T @ F @ T.T


def thin_shell(h, n):
    """Pure-bending flexibility factor of an inextensional thin ring section under free ovalization, n harmonics."""
    m = 2 * np.arange(1, n + 1)
    M = np.zeros((n + 1, n))
    M[np.arange(n), np.arange(n)] = (m + 1) / 2
    M[np.arange(n) + 1, np.arange(n)] = (m - 1) / 2
    K = np.diag((m * (m * m - 1) * h) ** 2 / (12 * (1 - NU ** 2)))
    a = np.linalg.solve(M.T @ M + K, M[0])
    e = np.eye(n + 1)[0] - M @ a
    return 1 / (e @ e + a @ K @ a)


def annular_shear_factor(nu, dt):
    """The annulus's energy-matched shear factor from the flexure solution of a straight elastic tube (free
    cylindrical faces), by Gauss-Legendre quadrature through the wall."""
    E1 = 1.0
    G1 = E1 / (2 * (1 + nu))
    b = 0.5
    a = b - 1 / dt
    area = math.pi * (b * b - a * a)
    c = 0.75 + nu / 2
    A, B = c * (a * a + b * b), c * a * a * b * b
    g, w = np.polynomial.legendre.leggauss(64)
    r = a + (b - a) * (g + 1) / 2
    w = w * (b - a) / 2
    p = A - B / r ** 2 - c * r * r
    qq = (0.25 - nu / 2) * r * r - A - B / r ** 2
    F = math.pi * G1 * np.sum(w * r * (p - qq))
    comp = math.pi * G1 * np.sum(w * r * (p ** 2 + qq ** 2)) / F ** 2
    return 1 / (G1 * area * comp)


# ------------------------------------------------------------------------------------------------ build
def build():
    fig, lim, margins = {}, {}, {}
    compliance = {}

    def limit(key, observed, bound, kind, digits=3, sense="max"):
        """kind "physical" (compared within its tolerance) or "roundoff" (a residual: its bound only); digits, the
        significant digits displayed (0: the block says only that it is within the bound)."""
        lim[key] = {"observed": float(observed), "bound": bound, "sense": sense, "kind": kind,
                    "digits": digits if kind == "physical" else 0}

    # --- the interior section compliance over the grid, with the grid's mesh measure and its own checks
    tors = {}
    conv_max = 0.0
    for rd in RDS:
        for dt in DTS:
            a, t = MESH[dt]
            C, tor = te.annulus_compliance(rd, 1.0, 1.0 / dt, n_around=a, n_through=t)
            Cc, _ = te.annulus_compliance(rd, 1.0, 1.0 / dt, n_around=(2 * a) // 3, n_through=max(1, t - 1))
            conv = float(np.max(np.abs(C - Cc) / np.sqrt(np.outer(np.diag(C), np.diag(C)))))
            conv_max = max(conv_max, conv)
            compliance[f"{rd}:{dt}"] = {"R_over_D": rd, "D_over_t": dt, "D": 1.0, "E": E, "nu": NU,
                                        "mesh": [a, t], "coarse_mesh": [(2 * a) // 3, max(1, t - 1)],
                                        "mesh_change": conv, "C": C.tolist()}
            tors[(rd, dt)] = tor
    limit("reference.mesh_change_on_grid", conv_max, 2e-3, "physical")
    EX = {k: np.array(v["C"]) for k, v in compliance.items()}

    # cut work against volume energy, and reciprocity, of the four dislocation problems on the grid
    worst = np.zeros(4)
    for (rd, dt), tor in tors.items():
        S, U = tor.S, tor.Em
        work0 = np.stack([rd * S[0, :2] + S[5, :2], S[2, :2]])
        work1 = np.stack([S[1, 2:4], S[3, 2:4] - rd * S[2, 2:4]])
        for i, (cut, vol) in enumerate([(work0, rd * U[:2, :2]), (work1, rd / 2 * (U[2:4, 2:4] + U[4:, 4:]))]):
            scale = np.sqrt(np.outer(vol.diagonal(), vol.diagonal()))
            worst[i] = max(worst[i], np.max(np.abs(cut - vol) / scale))
            worst[i + 2] = max(worst[i + 2], np.max(np.abs(cut - cut.T) / scale))
    limit("reference.cut_work_vs_volume_energy", worst[:2].max(), 1e-6, "roundoff")
    limit("reference.cut_reciprocity", worst[2:].max(), 1e-8, "roundoff")

    # straight limit: R = 1000 D against the Timoshenko straight beam with the energy-matched factor
    for dt in (5, 20, 100):
        C, _ = te.annulus_compliance(1000.0, 1.0, 1.0 / dt, n_around=64 if dt < 50 else 128, n_through=2)
        Cb, _ = te.beam_reference(1000.0, 1.0, 1.0 / dt)
        d = np.diag(C) / np.diag(Cb)
        off = np.max(np.abs(C - np.diag(np.diag(C))) / np.sqrt(np.outer(np.diag(C), np.diag(C))))
        limit(f"reference.straight_limit.Dt{dt}.diagonal", np.max(np.abs(d - 1)), 1.2e-4 if dt <= 20 else 2.2e-3,
              "physical")
        # displayed digits, each clear of a rounding boundary by more than its tolerance; at R = 1000 D the thinnest
        # wall's off-diagonal entries carry roundoff of a few parts in a thousand and are not displayed
        limit(f"reference.straight_limit.Dt{dt}.off_diagonal", off, 1e-3, "physical", {5: 3, 20: 2, 100: 0}[dt])

    # a thin rectangular plate section against the exact plane-stress energies (force through the centre)
    plate = 0.0
    for hr in (0.1, 0.3, 0.6, 1.0):
        h = hr
        b = h / 50
        X, conn = te.rect_mesh(1.0, h, b, 24, 2)
        C = te.Torus(X, conn, 1.0, 1.0, NU).compliance()
        Nv, Mv = -b, b
        normal = 0.5 * (C[0, 0] * Nv ** 2 + 2 * C[0, 5] * Nv * Mv + C[5, 5] * Mv ** 2) / b
        shear = 0.5 * C[1, 1] * b ** 2 / b
        n_ex, s_ex = rb.exact_energies(hr, NU)
        plate = max(plate, abs(normal / n_ex - 1), abs(shear / s_ex - 1))
    limit("reference.plane_stress_rectangular_bar", plate, 1e-5, "physical")

    # the annulus's shear factor from the straight tube's flexure solution, against the frame solver's
    ash = max(abs(annular_shear_factor(nu, dt) / fs.kappa_annulus(0.5 - 1 / dt, 0.5, nu) - 1)
              for nu in (0.0, 0.3, 0.45) for dt in (5, 20, 100))
    limit("reference.annular_shear_integral", ash, 1e-12, "roundoff")

    # --- section figures over the grid
    karman_low, karman_high, shell = [], [], []
    vr_r1, vn_r1, kin_r1, thick = [], [], [], []
    kfit_min = math.inf
    for rd in RDS:
        for dt in DTS:
            C = EX[f"{rd}:{dt}"]
            sec = fs.Section(1.0, 1.0 / dt, E, E / 2.6)
            rg = math.sqrt(sec.I / sec.A)
            coup = C[0, 5] / math.sqrt((1 / (E * sec.A)) * (1 / (E * sec.I)))
            ratio = coup / (rg / rd)
            rm = (sec.ro + sec.ri) / 2
            h = sec.t * rd / rm ** 2
            kin, kout = C[5, 5] * E * sec.I, C[4, 4] * E * sec.I
            kfit_min = min(kfit_min, kin, kout)
            vr, vn = C[1, 1] * sec.G * sec.As, C[2, 2] * sec.G * sec.As
            key = f"section.R{rd:g}.Dt{dt}"
            fig[key + ".coupling_over_plane_section"] = ratio
            fig[key + ".axial_over_straight"] = C[0, 0] * E * sec.A
            fig[key + ".k_in_matched"] = kin
            fig[key + ".k_out_matched"] = kout
            fig[key + ".h"] = h
            fig[key + f".k_in_over_{KS}"] = kin * h / THIN_SHELL_COEFF
            fig[key + ".shear_in_plane_over_straight"] = vr
            fig[key + ".shear_out_of_plane_over_straight"] = vn
            if dt in KARMAN_DT:
                (karman_low if h < KARMAN_H_SPLIT else karman_high).append((h, kin * h / THIN_SHELL_COEFF - 1))
            if dt in SHELL_SERIES_DT:
                shell.append(kin / thin_shell(h, SHELL_SERIES_TERMS))
            if rd == 1.0:
                vr_r1.append(vr)
                vn_r1.append(vn)
                kin_r1.append(kin)
            if dt <= 10:
                thick.append((vr, vn))
    ratios = [fig[f"section.R{rd:g}.Dt{dt}.coupling_over_plane_section"] for rd in RDS for dt in DTS]
    fig["section.coupling_over_plane_section.min"] = min(ratios)
    fig["section.coupling_over_plane_section.max"] = max(ratios)
    fig["section.R1.shear_in_plane_over_straight.range"] = [min(vr_r1), max(vr_r1)]
    fig["section.R1.shear_out_of_plane_over_straight.range"] = [min(vn_r1), max(vn_r1)]
    fig["section.R1.k_in_matched.range"] = [min(kin_r1), max(kin_r1)]
    fig["section.thick_walls.shear_in_plane_over_straight.range"] = [min(v for v, _ in thick), max(v for v, _ in thick)]
    fig["section.thick_walls.shear_out_of_plane_over_straight.range"] = [min(v for _, v in thick),
                                                                       max(v for _, v in thick)]
    kk = karman_key()
    fig[kk + f".h_below_{KARMAN_H_SPLIT:g}.h_range"] = [min(h for h, _ in karman_low), max(h for h, _ in karman_low)]
    fig[kk + f".h_below_{KARMAN_H_SPLIT:g}.largest_departure"] = max(abs(d) for _, d in karman_low)
    fig[kk + f".h_above_{KARMAN_H_SPLIT:g}.h_range"] = [min(h for h, _ in karman_high),
                                                       max(h for h, _ in karman_high)]
    fig[kk + f".h_above_{KARMAN_H_SPLIT:g}.departure_range"] = [min(d for _, d in karman_high),
                                                               max(d for _, d in karman_high)]
    limit("reference.thin_shell_series", max(abs(r - 1) for r in shell), 0.012, "physical")

    # --- frame solver in its limits
    sec = fs.Section(0.3, 0.02, E, E / 2.6)
    limit("frame_solver.quarter_circle_closed_form", quarter_closed_form(sec), 1e-13, "roundoff")
    limit("frame_solver.straight_timoshenko_closed_form", przemieniecki(sec), 1e-13, "roundoff")
    limit("frame_solver.polyline_192_vs_thin_shear", polyline(sec, 192), 1e-5, "physical")
    eb, tim = straight_limit(sec)
    limit("frame_solver.straight_limit.thin_vs_euler_bernoulli", eb, 1e-5, "physical", 1)  # ATOL decides: one digit
    limit("frame_solver.straight_limit.thin_shear_vs_timoshenko", tim, 1e-5, "physical", 1)
    for dt in STRAIGHT_LIMIT_DT:
        s = fs.Section(STRAIGHT_D, STRAIGHT_D / dt, E, E / 2.6)
