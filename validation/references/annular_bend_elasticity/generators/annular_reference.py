def rounded(x):
    if isinstance(x, float):
        return float(f"{x:.12g}")
    if isinstance(x, list):
        return [rounded(v) for v in x]
    if isinstance(x, dict):
        return {k: rounded(v) for k, v in x.items()}
    return x


def dumps(obj):
    return json.dumps(rounded(obj), indent=1, sort_keys=True) + "\n"


def readme_with(block):
    text = (PKG / "README.md").read_text(encoding="utf-8")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + BEGIN + "\n" + block + END + tail


def sums_text():
    return "".join(f"{hashlib.sha256((PKG / p).read_bytes()).hexdigest()}  {p}\n" for p in FILES)


def compare(a, b, path, out):
    if isinstance(b, dict):
        if not isinstance(a, dict) or set(a) != set(b):
            out.append(f"{path}: keys differ: {sorted(set(a) ^ set(b)) if isinstance(a, dict) else type(a)}")
            return
        for k in b:
            compare(a[k], b[k], f"{path}.{k}" if path else k, out)
    elif isinstance(b, list):
        if not isinstance(a, list) or len(a) != len(b):
            out.append(f"{path}: {a!r} against {b!r}")
            return
        for i, (x, y) in enumerate(zip(a, b)):
            compare(x, y, f"{path}[{i}]", out)
    elif isinstance(b, bool) or isinstance(b, int) and not isinstance(b, bool) and isinstance(a, int):
        if a != b:
            out.append(f"{path}: {a!r} against committed {b!r}")
    elif isinstance(b, (int, float)):
        if not isinstance(a, (int, float)) or abs(a - b) > max(RTOL * abs(b), ATOL):
            out.append(f"{path}: {a!r} against committed {b!r}")
    elif a != b:
        out.append(f"{path}: {a!r} against committed {b!r}")


def main(argv):
    write = argv[1:] == ["--write"]
    if argv[1:] not in ([], ["--check"], ["--write"]):
        raise SystemExit("usage: annular_reference.py [--check | --write]")
    inputs, fig, lim, compliance, paths, read = build()
    problems = []
    if len(read) != len(paths) or not read:
        problems.append(f"model documents matching {MODELS_GLOB}: {len(paths)} found, {len(read)} read")
    for k, v in lim.items():
        bad = v["observed"] > v["bound"] if v["sense"] == "max" else v["observed"] < v["bound"]
        if bad:
            problems.append(f"limit {k}: observed {v['observed']:.3e}, bound {v['bound']:g} ({v['sense']})")
    for name in (WORKFLOW, REGISTRY):
        if MODELS_GLOB not in (ROOT / name).read_text(encoding="utf-8"):
            problems.append(f"{name} does not name {MODELS_GLOB}, the documents this package reads")
    problems += lim021_problems(fig)
    block = render_block(inputs, fig, lim)
    figures = {"inputs": inputs, "figures": fig, "limits": lim}
    if write:
        if problems:
            print("\n".join(problems))
            return 1
        (PKG / "compliance.json").write_text(dumps(compliance), encoding="utf-8")
        (PKG / "figures.json").write_text(dumps(figures), encoding="utf-8")
        (PKG / "README.md").write_text(readme_with(block), encoding="utf-8")
        (PKG / "SHA256SUMS").write_text(sums_text(), encoding="utf-8")
        print(f"wrote {len(fig)} figures, {len(lim)} limit checks, {len(compliance)} compliances")
        return 0
    committed = json.loads((PKG / "figures.json").read_text(encoding="utf-8"))
    if committed["inputs"]["models"] != read:
        problems.append(f"model documents read {read}, figures.json records {committed['inputs']['models']}")
    compare({"inputs": inputs, "figures": rounded(fig)}, {"inputs": committed["inputs"],
                                                         "figures": committed["figures"]}, "", problems)
    if {k: (v["bound"], v["sense"], v["shown"]) for k, v in lim.items()} != \
            {k: (v["bound"], v["sense"], v["shown"]) for k, v in committed["limits"].items()}:
        problems.append("the limit checks or their bounds differ from figures.json")
    old = json.loads((PKG / "compliance.json").read_text(encoding="utf-8"))
    if set(old) != set(compliance):
        problems.append("compliance.json holds other geometries")
    for k, v in compliance.items():
        if k in old:
            a, b = np.array(v["C"]), np.array(old[k]["C"])
            scale = np.sqrt(np.outer(np.abs(np.diag(b)), np.abs(np.diag(b))))
            if np.max(np.abs(a - b) / scale) > RTOL or old[k]["mesh"] != v["mesh"]:
                problems.append(f"compliance.json {k} differs from the recomputed compliance")
    if (PKG / "README.md").read_text(encoding="utf-8") != readme_with(block):
        problems.append("README.md: the generated block differs from the rendering of the recomputed figures")
    prose = (PKG / "README.md").read_text(encoding="utf-8")
    prose = prose.split(BEGIN)[0] + prose.split(END)[1]
    left = leftover_numbers(prose)
    if left:
        problems.append(f"README.md states numbers outside its generated block: {left}")
    present = sorted(p.relative_to(PKG).as_posix() for p in PKG.rglob("*")
                     if p.is_file() and "__pycache__" not in p.parts)
    if present != sorted((*FILES, "SHA256SUMS")):
        problems.append(f"package files {present}, expected {sorted((*FILES, 'SHA256SUMS'))}")
    elif (PKG / "SHA256SUMS").read_text(encoding="utf-8") != sums_text():
        problems.append("SHA256SUMS does not match the package's files")
    if problems:
        print("annular_bend_elasticity check FAILED:\n  " + "\n  ".join(problems))
        return 1
    print(f"annular_bend_elasticity check passed: {len(fig)} figures, {len(lim)} limit checks, "
          f"{len(compliance)} compliances, {len(read)} model documents read")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
