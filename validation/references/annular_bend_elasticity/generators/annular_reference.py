def quarter_closed_form(sec, R=0.45):
    pi = math.pi
    EI, EA, GJ, GAs = E * sec.I, E * sec.A, sec.G * sec.J, sec.G * sec.As
    worst = 0.0
    for kin, kout in ((1, 1), (3, 3), (7, 2.5)):
        for mode in ("off", "unscaled", "scaled"):
            si, so = (kin, kout) if mode == "scaled" else (1.0, 1.0)
            sh = 0.0 if mode == "off" else 1.0
            b, bo, g = kin * R / EI, kout * R / EI, R / GJ
            F = np.zeros((6, 6))
            F[0, 0] = b * R * R * (3 * pi / 4 - 2) + R / EA * pi / 4 + sh * si * R / GAs * pi / 4
            F[1, 1] = b * R * R * pi / 4 + R / EA * pi / 4 + sh * si * R / GAs * pi / 4
            F[0, 1] = F[1, 0] = b * R * R / 2 - R / (2 * EA) + sh * si * R / (2 * GAs)
            F[5, 5] = b * pi / 2
            F[0, 5] = F[5, 0] = -b * R * (pi / 2 - 1)
            F[1, 5] = F[5, 1] = -b * R
            F[2, 2] = bo * R * R * pi / 4 + g * R * R * (3 * pi / 4 - 2) + sh * so * R * pi / (2 * GAs)
            F[3, 3] = F[4, 4] = bo * pi / 4 + g * pi / 4
            F[3, 4] = F[4, 3] = (bo - g) / 2
            F[2, 3] = F[3, 2] = bo * R * pi / 4 + g * R * (pi / 4 - 1)
            F[2, 4] = F[4, 2] = bo * R / 2 + g * R / 2
            Fa = fs.Arc([R, 0, 0], [0, R, 0], R, [1, 1, 0], sec, kin, kout, mode).tip_flexibility()
            worst = max(worst, float(np.max(np.abs(Fa - F)) / np.max(np.abs(F))))
    return worst


def przemieniecki(sec, L=2.3):
    K = fs.Straight([0, 0, 0], [L, 0, 0], sec, True, [0, 1, 0]).stiffness()
    EI = E * sec.I
    ph = 12 * EI / (sec.G * sec.As * L * L)
    ref = {(1, 1): 12 * EI / (L ** 3 * (1 + ph)), (1, 5): 6 * EI / (L ** 2 * (1 + ph)),
           (5, 5): (4 + ph) * EI / (L * (1 + ph)), (5, 11): (2 - ph) * EI / (L * (1 + ph)),
           (2, 4): -6 * EI / (L ** 2 * (1 + ph)), (0, 0): E * sec.A / L, (3, 3): sec.G * sec.J / L,
           (1, 7): -12 * EI / (L ** 3 * (1 + ph))}
    return max(abs(K[i, j] - v) / abs(v) for (i, j), v in ref.items())


def polyline(sec, N, R=0.45):
    arc = fs.Arc([R, 0, 0], [0, R, 0], R, [1, 1, 0], sec, 1, 1, "unscaled")
    Fa = arc.tip_flexibility()
    nodes = [arc.pos(arc.phi * s / N) for s in range(N + 1)]
    Ft = np.zeros((6, 6))
    for s in range(N):
        Fm = fs.Straight(nodes[s], nodes[s + 1], sec, True, arc.n).tip_flexibility()
        T = np.eye(6)
        T[3:, :3] = fs.skew(arc.xj - nodes[s + 1])
        Ft += T.T @ Fm @ T
    return float(np.max(np.abs(Ft - Fa)) / np.max(np.abs(Fa)))


def straight_limit(sec, L=1.2, R_over_L=1000):
    """At fixed arc length L and R = 1000 L, unit factors: the thin arc against the Euler-Bernoulli cantilever and
    the thin arc with shear against the Timoshenko cantilever (transverse tip flexibilities, both directions)."""
    stT = fs.Straight([0, 0, 0], [L, 0, 0], sec, True, [0, 1, 0]).tip_flexibility_local()
    stE = fs.Straight([0, 0, 0], [L, 0, 0], sec, False, [0, 1, 0]).tip_flexibility_local()
    R = R_over_L * L
    ph = L / R
    xj = np.array([R * math.sin(ph), R * (1 - math.cos(ph)), 0])
    out = []
    for mode, ref in (("off", stE), ("unscaled", stT)):
        a = fs.Arc([0, 0, 0.0], xj, R, [0, -1.0, 0], sec, 1, 1, mode)
        T = np.zeros((6, 6))
        T[:3, :3] = T[3:, 3:] = a.frame(a.phi)
        Fl = T @ a.tip_flexibility() @ T.T
        out.append(max(abs(Fl[1, 1] / ref[1, 1] - 1), abs(Fl[2, 2] / ref[2, 2] - 1)))
    return out


