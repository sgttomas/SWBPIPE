def leftover_numbers(text):
    for pat in IDENTIFIERS:
        text = re.sub(pat, " ", text)
    return re.findall(r"\d[\d.,]*", text)


def lim021_problems(f):
    doc = (ROOT / LIMITATIONS).read_text(encoding="utf-8")
    m = re.search(r"^### LIM-021 .*?(?=^### )", doc, re.S | re.M)
    if not m:
        return [f"{LIMITATIONS}: no LIM-021 entry"]
    text = m.group(0)
    problems = []
    for phrase, _ in lim_phrases(f):
        if phrase not in text:
            problems.append(f"LIM-021 does not state {phrase!r}")
        text = text.replace(phrase, " ")
    left = leftover_numbers(text)
    if left:
        problems.append(f"LIM-021 states numbers no key backs: {left}")
    return problems


def table(rows, head):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


