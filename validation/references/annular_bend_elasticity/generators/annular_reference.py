def lmodel(L, R, dt, k, D=1.0):
    """Planar L: two equal legs of length L joined by a 90-degree bend of radius R, both ends anchored; a uniform
    rise of 100 degC with alpha 1e-5 (free growth 0.1%) and a point force normal to the plane at the bend's far end."""
    t = D / dt
    nodes = [("A", (0, 0, 0)), ("b1", (L, 0, 0)), ("b2", (L + R, R, 0)), ("B", (L + R, L + R, 0))]
    sec = {"outside_diameter": {"unit": "m", "value": D}, "wall_thickness": {"unit": "m", "value": t}}
    pipes = [("P1", "A", "b1", (0, 1, 0)), ("BEND", "b1", "b2", (1, -1, 0)), ("P2", "b2", "B", (-1, 0, 0))]
    return {
        "nodes": [{"id": n, "position": dict(zip("xyz", p))} for n, p in nodes],
        "materials": [{"id": "mat", "elastic_modulus": {"unit": "Pa", "value": E},
                       "shear_modulus": {"unit": "Pa", "value": E / 2.6},
                       "thermal_expansion_coefficient": {"unit": "1/degC", "value": 1e-5}}],
        "pipe_segments": [{"id": i, "from": a, "to": b, "material": "mat", "section": sec,
                           "y_reference": dict(zip("xyz", y))} for i, a, b, y in pipes],
        "components": [{"kind": "bend", "mechanics_interface": {"solver_consumption": "curved_bend_macro_element"},
                        "geometry": {"bend_pipe_ref": "BEND", "bend_radius": {"unit": "m", "value": R}},
                        "modifiers": {"flexibility_factor_user_value": {"unit": "none", "value": k}}}],
        "supports": [{"id": "sA", "node": "A", "family": "anchor", "restraints": list(fs.DOFS)},
                     {"id": "sB", "node": "B", "family": "anchor", "restraints": list(fs.DOFS)}],
        "load_cases": [
            {"id": "thermal", "primitive_loads": [
                {"category": "thermal", "magnitude": {"unit": "degC", "value": 100.0}, "target": {"pipe": p}}
                for p in ("P1", "BEND", "P2")]},
            {"id": "outplane", "primitive_loads": [
                {"category": "concentrated_force", "direction": "global_z", "magnitude": {"unit": "N", "value": -1.0e4},
                 "target": {"node": "b2"}}]}]}


def l_reactions(res, case, L):
    """The twelve anchor reaction components of an L-run, moments divided by the leg length."""
    r = res["cases"][case]["reactions"]
    return np.array([r[s][c] / (L if c[0] == "M" else 1.0) for s in ("sA", "sB") for c in fs.FORCES])


def l_measure(qm, qr):
    """L-run measure: the largest componentwise difference over the largest reference component (one scale for
    forces and moments / L), signed by the change in magnitude of the reference's largest component."""
    j = int(np.argmax(np.abs(qr)))
    v = np.max(np.abs(qm - qr)) / np.max(np.abs(qr))
    return math.copysign(v, abs(qm[j]) - abs(qr[j]))


def bench_measure(res_m, res_r):
    """Benchmark measure, per load case: forces and moments each normalized by their own largest reference
    component over every support; the larger of the two, in per cent."""
    out = {}
    for case in res_r["cases"]:
        def vec(res):
            return np.array([[res["cases"][case]["reactions"][sid][k] for k in fs.FORCES]
                             for sid in sorted(res["cases"][case]["reactions"])])
        a, b = vec(res_m), vec(res_r)
        m = 0.0
        for j in (0, 3):
            s = np.max(np.abs(b[:, j:j + 3]))
            if s > 0:
                m = max(m, 100 * np.max(np.abs(a[:, j:j + 3] - b[:, j:j + 3])) / s)
        out[case] = m
    return out


def code_factor(sec, R):
    rm = (sec.ro + sec.ri) / 2
    return max(1.0, 1.65 * rm * rm / (sec.t * R))


def tally(pairs, tag, margins):
    """(nearer, tied, further, largest gain, largest loss) of (reference model error, compared model error) in
    percentage points; records the smallest distance of a deciding difference from the tie band."""
    d = [abs(t) - abs(m) for t, m in pairs]
    margins[tag] = min(min(abs(x - TIE), abs(x + TIE)) for x in d)
    near = [x for x in d if x > TIE]
    far = [x for x in d if x < -TIE]
    return [len(near), len(d) - len(near) - len(far), len(far)], max(near, default=0.0), -min(far, default=0.0)


def arc_for(R, phi, sec, **kw):
    xi = np.array([R, 0.0, 0.0])
    xj = np.array([R * math.cos(phi), R * math.sin(phi), 0.0])
    mid = 0.5 * (xi + xj)
    yref = mid if np.linalg.norm(mid) > 1e-12 else np.array([0, 1.0, 0])
    if phi > math.pi - 1e-9:
        yref = np.array([0, 1.0, 0])  # semicircle: the chord passes through the centre; bow toward +y
    return fs.Arc(xi, xj, R, yref, sec, **kw)


def tip_local(arc):
    F = arc.tip_flexibility()
    T = np.zeros((6, 6))
    T[:3, :3] = T[3:, 3:] = arc.frame(arc.phi)
    return T @ F @ T.T


def thin_shell(h, n):
    """Pure-bending flexibility factor of an inextensional thin ring section under free ovalization, n harmonics."""
    m = 2 * np.arange(1, n + 1)
    M = np.zeros((n + 1, n))
    M[np.arange(n), np.arange(n)] = (m + 1) / 2
    M[np.arange(n) + 1, np.arange(n)] = (m - 1) / 2
    K = np.diag((m * (m * m - 1) * h) ** 2 / (12 * (1 - NU ** 2)))
    a = np.linalg.solve(M.T @ M + K, M[0])
    e = np.eye(n + 1)[0] - M @ a
    return 1 / (e @ e + a @ K @ a)


def annular_shear_factor(nu, dt):
    """The annulus's energy-matched shear factor from the flexure solution of a straight elastic tube (free
    cylindrical faces), by Gauss-Legendre quadrature through the wall."""
    E1 = 1.0
    G1 = E1 / (2 * (1 + nu))
    b = 0.5
    a = b - 1 / dt
    area = math.pi * (b * b - a * a)
    c = 0.75 + nu / 2
    A, B = c * (a * a + b * b), c * a * a * b * b
    g, w = np.polynomial.legendre.leggauss(64)
    r = a + (b - a) * (g + 1) / 2
    w = w * (b - a) / 2
    p = A - B / r ** 2 - c * r * r
    qq = (0.25 - nu / 2) * r * r - A - B / r ** 2
    F = math.pi * G1 * np.sum(w * r * (p - qq))
    comp = math.pi * G1 * np.sum(w * r * (p ** 2 + qq ** 2)) / F ** 2
    return 1 / (G1 * area * comp)


