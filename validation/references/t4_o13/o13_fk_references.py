"""O-13: writes `o13_fk_references.txt`, the FK recovery-certificate tests'
form of `o13_candidates.json` (standard library only; `python3 -I
o13_fk_references.py` in this directory).

Each 40-significant-digit reference value x becomes three binary64 terms
t0 = RN(x), t1 = RN(x - t0), t2 = RN(x - t0 - t1) (hex bits); the residual
is below 2^-150 |x|. The tests add the file's `relative` allowance (the
40-digit rounding, 5e-40 |x|, plus that residual) to every comparison.
Inputs are binary64 values written by `repr`, so `float()` returns their bits.
"""
import json
import struct
from decimal import Decimal
from fractions import Fraction

FIELDS = ("xi", "xj", "R", "y", "E", "G", "A", "I", "J", "kin", "kout")


def bits(x):
    return struct.pack(">d", x).hex()


def terms(text):
    exact = Fraction(Decimal(text))
    out = []
    rest = exact
    for _ in range(3):
        t = float(rest)
        out.append(t)
        rest -= Fraction(t)
    return " ".join(bits(t) for t in out)


def flat(inputs):
    values = []
    for key in FIELDS:
        v = inputs[key]
        values.extend(v if isinstance(v, list) else [v])
    return " ".join(bits(float(v)) for v in values)


def main():
    data = json.load(open("o13_candidates.json"))
    lines = ["# O-13 FK references (generated by o13_fk_references.py from o13_candidates.json)",
             "relative 1e-39"]
    inputs = {}
    for case in data["stiffness"]:
        inputs[case["id"]] = case["inputs"]
        lines.append("stiffness " + case["id"])
        lines.append("args " + flat(case["inputs"]))
        for r, row in enumerate(case["K"]):
            for c, value in enumerate(row):
                lines.append("k %d %d %s" % (r, c, terms(value)))
        lines.append("end")
    for case in data["element_rows"]:
        lines.append("row %s|%s" % (case["id"], repr(case["Q"])))
        lines.append("args " + flat(inputs[case["id"]]))
        lines.append("u " + " ".join(bits(float(v)) for v in case["u"]))
        lines.append("py " + " ".join(bits(float(v)) for v in case["py"]))
        for k, value in enumerate(case["f_exact"]):
            lines.append("f %d %s" % (k, terms(value)))
        lines.append("end")
    with open("o13_fk_references.txt", "w") as out:
        out.write("\n".join(lines) + "\n")
    print("stiffness %d, rows %d" % (len(data["stiffness"]), len(data["element_rows"])))


if __name__ == "__main__":
    main()
