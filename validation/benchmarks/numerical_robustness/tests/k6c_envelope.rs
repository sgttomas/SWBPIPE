fn fields(e: Estimate) -> [u128; 5] {
    [e.model, e.fixed, e.decide, e.max, e.sel128]
}
#[test]
fn all_193_independently_reviewed_reference_values_and_source_drop() {
    let (cases, facts) = load_all_described();
    assert_eq!(EXPECTED.len(), 193);
    assert_eq!(CALLERS.len(), EXPECTED.len());
    for ((id, requested, moving), (phase_r, phase_m, join_r, join_m)) in
        EXPECTED.iter().zip(CALLERS)
    {
        let case = cases.iter().find(|c| c.id == *id).unwrap();
        let model = case.model.as_ref().unwrap();
        let source = PrimitiveSource::new(model.source_parts()).unwrap();
        let counts = scale::counts(model, &source);
        let family = FAMILY_FILES
            .iter()
            .position(|(f, _)| *f == case.family)
            .unwrap();
        let context = VrEstimateContext::capture(
            case,
            model,
            &source,
            &counts,
            facts[family],
            None,
            VrInvocation::single_case_family_reference(&case.id),
            PopulationPolicy::NodesAndFreeDofsUpper,
        )
        .unwrap();
        drop(source);
        let e = estimate(
            &context,
            &ReferenceKernelProfile::source40129_rust1971_aarch64_v1(),
            &ReferenceVRProfile::source40129_rust1971_aarch64_v1(),
        )
        .unwrap();
        assert_eq!(e.caller_requested, *phase_r, "{id} requested caller phases");
        assert_eq!(e.caller_moving, *phase_m, "{id} moving caller phases");
        assert_eq!(e.joins_requested, *join_r, "{id} requested kernel addends");
        assert_eq!(e.joins_moving, *join_m, "{id} moving kernel addends");
        assert_eq!(fields(e.requested), *requested, "{id} requested");
        assert_eq!(fields(e.moving), *moving, "{id} moving");
    }
}

