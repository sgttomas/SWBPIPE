#[test]
fn embedded_actual_cli_policy_matches_independent_values_at_bound_path_lengths() {
    let (cases, facts) = load_all_described();
    let family = FAMILY_FILES
        .iter()
        .position(|(f, _)| *f == "RF-LARGE")
        .unwrap();
    assert_eq!(CLI_EXPECTED.len(), 12);
    for (id, manifest_len, executable_len, requested, moving, cr, cm, jr, jm) in CLI_EXPECTED {
        let case = cases.iter().find(|c| c.id == *id).unwrap();
        let model = case.model.as_ref().unwrap();
        assert!(model.members.len() <= 100);
        let source = PrimitiveSource::new(model.source_parts()).unwrap();
        let counts = scale::counts(model, &source);
        // Only lengths enter the arithmetic. These synthetic borrowed names do
        // not claim an executable or input binding for a machine-specific path.
        let manifest = "m".repeat(*manifest_len);
        let executable = "e".repeat(*executable_len);
        let mut args = ArgumentFacts::default();
        for token in [
            executable.as_str(),
            "--case",
            &case.id,
            "--heap-cap-bytes",
            "536870912",
            "--counts-only",
        ] {
            args.observe(token);
        }
        let invocation = VrInvocation::actual(&manifest, &case.id, None, args, true);
        let context = VrEstimateContext::capture(
            case,
            model,
            &source,
            &counts,
            facts[family],
            None,
            invocation,
            PopulationPolicy::Exact {
                bodies: counts.bodies as u128,
                free_blocks: counts.blocks as u128,
            },
        )
        .unwrap();
        drop(source);
        let e = estimate(
            &context,
            &ReferenceKernelProfile::source40129_rust1971_aarch64_v1(),
            &ReferenceVRProfile::source40129_rust1971_aarch64_v1(),
        )
        .unwrap();
        assert_eq!(fields(e.requested), *requested, "{id} requested");
        assert_eq!(fields(e.moving), *moving, "{id} moving");
        assert_eq!(e.caller_requested, *cr, "{id} caller requested");
        assert_eq!(e.caller_moving, *cm, "{id} caller moving");
        assert_eq!(e.joins_requested, *jr, "{id} joins requested");
        assert_eq!(e.joins_moving, *jm, "{id} joins moving");
    }
}

