def git(repo, *args, **kw):
    return subprocess.run(['git', '-C', repo] + list(args), check=True, capture_output=True, **kw)


def apply_edits(copy, edits):
    diffs = []
    for rel, old, new, count in edits:
        path = os.path.join(copy, P, rel)
        with open(path) as fh:
            text = fh.read()
        found = text.count(old)
        if found != count:
            raise SystemExit('%s: %r found %d times, expected %d' % (rel, old[:60], found, count))
        mutated = text.replace(old, new)
        diffs += difflib.unified_diff(text.splitlines(True), mutated.splitlines(True),
                                      'a/' + P + '/' + rel, 'b/' + P + '/' + rel)
        with open(path, 'w') as fh:
            fh.write(mutated)
    return ''.join(diffs)


def dry_run(top, rev, plan):
    for mid, _, _, _, edits, _ in plan:
        for rel, old, _, count in edits:
            text = git(top, 'show', '%s:%s/%s' % (rev, P, rel), text=True).stdout
            found = text.count(old)
            print('%-9s %-40s %d/%d %s' % (mid, rel.split('/')[-1], found, count,
                                          'OK' if found == count else 'MISMATCH'))


def case_hashes(vr_dir):
    d = os.path.join(vr_dir, 'cases')
    out = {}
    for name in sorted(os.listdir(d)):
        p = os.path.join(d, name)
        if os.path.isfile(p):
            with open(p, 'rb') as fh:
                out[name] = hashlib.sha256(fh.read()).hexdigest()
    return out


def panics(text):
    """(test, first message line) of every panic, in order."""
    out, lines = [], text.splitlines()
    for k, line in enumerate(lines):
        m = re.match(r"^thread '([^']+)'(?: \(\d+\))? panicked at ([^:]+:\d+):\d+:", line)
        if m:
            msg = lines[k + 1] if k + 1 < len(lines) else ''
            out.append('%s @ %s: %s' % (m.group(1), m.group(2), sanitize(msg)[:300]))
    return out


def failure_lines(text, limit=12):
    keep = [sanitize(l)[:300] for l in text.splitlines() if 'FAILURE' in l]
    return keep[:limit], len(keep)


def run_one(entry, args, top, rev):
    mid, maps_to, what, expected, edits, gen = entry
    copy = os.path.join(args.copies, mid)
    if os.path.exists(copy):
        shutil.rmtree(copy)
    os.makedirs(copy)
    # Two archives: an exclusion also drops explicitly named paths beneath it.
    for paths in ([P, ':(exclude)%s/execution' % P], ['%s/%s' % (P, g) for g in GEN_INPUTS]):
        archive = subprocess.Popen(['git', '-C', top, 'archive', rev, '--'] + paths, stdout=subprocess.PIPE)
        subprocess.run(['tar', '-x', '-C', copy], stdin=archive.stdout, check=True)
        if archive.wait():
            raise SystemExit('git archive failed')
    overlay = {}
    for rel in args.overlay:
        src = os.path.join(top, P, rel)
        with open(src, 'rb') as fh:
            data = fh.read()
        dst = os.path.join(copy, P, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, 'wb') as fh:
            fh.write(data)
        overlay[P + '/' + rel] = hashlib.sha256(data).hexdigest()
    diff = apply_edits(copy, edits)
    logs = os.path.join(args.out, 'logs')
    with open(os.path.join(logs, '%s.diff' % mid), 'w') as fh:
        fh.write(diff)
    vr_dir = os.path.join(copy, P, VR)
    row = {'id': mid, 'maps_to': maps_to, 'what': what, 'expected_kill': expected, 'rev': rev,
           'run': args.label, 'overlay': overlay, 'generator_run': gen, 'edit_lines': sum(1 for l in diff.splitlines()
                                                   if l[:1] in '+-' and l[:3] not in ('+++', '---'))}
    if gen:
        before = case_hashes(vr_dir)
        t0 = time.monotonic()
        g = subprocess.run([sys.executable, '-B', os.path.join(vr_dir, 'cases/gen_vk_cases.py')],
                           capture_output=True, text=True)
        row['generator_seconds'] = round(time.monotonic() - t0, 1)
        row['generator_exit'] = g.returncode
        with open(os.path.join(logs, '%s.gen.log' % mid), 'w') as fh:
            fh.write(sanitize(g.stdout + g.stderr))
        after = case_hashes(vr_dir)
        row['case_files_changed'] = sorted(n for n in set(before) | set(after) if before.get(n) != after.get(n))
    env = dict(os.environ)
    env.pop('FK_SEEDED_FAULT', None)
    env.update({'CARGO_TARGET_DIR': os.path.join(copy, 'target'), 'CARGO_INCREMENTAL': '0',
                'RUST_TEST_THREADS': '2'})
    t0 = time.monotonic()
    build = subprocess.run(['cargo', 'test', '--offline', '--locked', '-j', '4', '--no-run'],
                           cwd=vr_dir, env=env, capture_output=True, text=True)
    row['build_seconds'] = round(time.monotonic() - t0, 1)
    row['build_ok'] = build.returncode == 0
    text = build.stdout + build.stderr
    if row['build_ok']:
        t0 = time.monotonic()
        try:
            proc = subprocess.run(['cargo', 'test', '--offline', '--locked', '-j', '4', '--no-fail-fast',
                                   '--', '--nocapture'], cwd=vr_dir, env=env, capture_output=True,
                                  text=True, timeout=args.timeout)
            text += proc.stdout + proc.stderr
            row['exit_code'], row['timed_out'] = proc.returncode, False
        except subprocess.TimeoutExpired as e:
            out = e.stdout.decode(errors='replace') if isinstance(e.stdout, bytes) else (e.stdout or '')
            text += out
            row['exit_code'], row['timed_out'] = None, True
        row['test_seconds'] = round(time.monotonic() - t0, 1)
    with open(os.path.join(logs, '%s.log' % mid), 'w') as fh:
        fh.write(sanitize(text))
    tests = [(m.group(1), m.group(2)) for m in (TEST_LINE.match(l) for l in text.splitlines()) if m]
    row['tests_run'] = len(tests)
    row['failing_tests'] = sorted({n for n, s in tests if s == 'FAILED'})
    row['panics'] = panics(text)[:12]
    row['failure_samples'], row['failure_lines'] = failure_lines(text)
    if not row['build_ok']:
        row['verdict'] = 'BUILD FAILS'
    elif row.get('timed_out'):
        row['verdict'] = 'TIMEOUT'
    elif mid.startswith('NONE'):
        clean = not row['failing_tests'] and row['exit_code'] == 0 and row['tests_run'] == args.tests
        if gen:
            clean = clean and row['generator_exit'] == 0 and not row['case_files_changed']
        row['verdict'] = 'pass' if clean else 'CONTROL FAILS'
    elif gen and row.get('generator_exit'):
        row['verdict'] = 'GENERATOR FAILS'
    else:
        row['verdict'] = 'killed' if row['failing_tests'] else 'SURVIVED'
    if not args.keep:
        shutil.rmtree(os.path.join(copy, 'target'), ignore_errors=True)
    return row


def rebuild(out):
    """Re-reads each run's test results from its (sanitized) log; the other
    fields, and the verdict, stay as the run recorded them."""
    path = os.path.join(out, 'harness_matrix.jsonl')
    rows = [json.loads(l) for l in open(path)]
    for row in rows:
        with open(os.path.join(out, 'logs', '%s.log' % row['id'])) as fh:
            text = fh.read()
        tests = [(m.group(1), m.group(2)) for m in (TEST_LINE.match(l) for l in text.splitlines()) if m]
        assert row['tests_run'] == len(tests), row['id']
        assert row['failing_tests'] == sorted({n for n, s in tests if s == 'FAILED'}), row['id']
        row['panics'] = panics(text)[:12]
        row['failure_samples'], row['failure_lines'] = failure_lines(text)
    with open(path, 'w') as fh:
        for r in rows:
            fh.write(json.dumps(r, sort_keys=True, ensure_ascii=False) + '\n')
    for r in rows:
        print('%-9s %-15s %s' % (r['id'], r['verdict'], (r['panics'] or [''])[0][:150]))
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--copies', required=True)
    ap.add_argument('--rev', default='HEAD')
    ap.add_argument('--only')
    ap.add_argument('--timeout', type=int, default=1800)
    ap.add_argument('--tests', type=int, default=40, help="the clean copy's test count")
    ap.add_argument('--dry-run', action='store_true', help='check every edit against the revision; run nothing')
    ap.add_argument('--keep', action='store_true', help="keep each copy's target")
    ap.add_argument('--label', default='c1', help="this run's label, recorded in each row")
    ap.add_argument('--overlay', nargs='*', default=[],
                    help='files (paths under the piping tree) copied from the working tree into every copy')
    ap.add_argument('--carry', help="an earlier run's harness_matrix.jsonl")
    ap.add_argument('--carry-label', help="the earlier run's label, where its rows carry none")
    ap.add_argument('--from-logs', action='store_true',
                    help="re-read each run's test results from its log into harness_matrix.jsonl; run nothing")
    args = ap.parse_args()
    if args.from_logs:
        return rebuild(args.out)
    top = subprocess.run(['git', 'rev-parse', '--show-toplevel'], capture_output=True, text=True,
                         check=True).stdout.strip()
    rev = git(top, 'rev-parse', args.rev, text=True).stdout.strip()
    only = set(args.only.split(',')) if args.only else None
    plan = [c for c in CONTROLS if only is None or c[0] in only or c[0] == 'NONE']
    plan += [m for m in MUTANTS if only is None or m[0] in only]
    if args.dry_run:
        dry_run(top, rev, plan)
        return 0
    os.makedirs(os.path.join(args.out, 'logs'), exist_ok=True)
    os.makedirs(args.copies, exist_ok=True)
    rows, status = [], 0
    for entry in plan:
        row = run_one(entry, args, top, rev)
        rows.append(row)
        if row['verdict'] not in ('pass', 'killed'):
            status = 1
        print('%-9s %-15s build %5.1fs tests %6ss  failing %s' % (
            row['id'], row['verdict'], row['build_seconds'], row.get('test_seconds'),
            row['failing_tests']), flush=True)
        if row['id'] == 'NONE' and row['verdict'] != 'pass':
            print('NONE fails: stop')
            break
        write_matrix(args, rows)
    write_matrix(args, rows)
    return status


def write_matrix(args, rows):
    """This run's rows, with an earlier run's rows carried for the ids not
    re-run, in plan order."""
    out = {r['id']: r for r in rows}
    if args.carry:
        for line in open(args.carry):
            old = json.loads(line)
            old.setdefault('run', args.carry_label)
            if old['id'] in out:
                out[old['id']].setdefault('previous', {
                    'run': old['run'], 'verdict': old['verdict'], 'failing_tests': old['failing_tests'],
                    'tests_run': old['tests_run']})
            else:
                out[old['id']] = old
    order = [c[0] for c in CONTROLS + MUTANTS]
    with open(os.path.join(args.out, 'harness_matrix.jsonl'), 'w') as fh:
        for mid in sorted(out, key=order.index):
            fh.write(json.dumps(out[mid], sort_keys=True, ensure_ascii=False) + '\n')


if __name__ == '__main__':
    sys.exit(main())
