#!/usr/bin/env python3
"""Generate the RT-V8 P7 scope of DEC-058 check (c): tools/release/provenance_scope.json.

Owner decision (2026-10-28, P7 as recommended): check (c) does not block the
product's own provenance labels inside invented fixtures. This generator
derives the scope from the repository, so it is never hand-typed:

1. Members: every JSON file the public export ships (the export's own
   `select_files`), read from the working tree of a clean checkout.
2. Flagged records: the provenance records check (c) would flag in each file,
   using the scan's own record walk, violation rules and trusted schema
   manifest.
3. Eligibility, by declaration only (a path never qualifies a file): the file
   must hold at least one provenance record (an object with
   `redistribution_status`) that declares invented content, either
   `redistribution_status: "invented_non_engineering_example"` or the word
   "invented" in its `origin`, `source_name` or `contributor_certification`.
4. Each eligible file with flagged records becomes one entry: its path, its
   SHA-256, the exact (redistribution_status, review_status) pairs of its
   flagged records, and the declaring field as the reason. Files that are not
   eligible stay unscoped, so their records remain check (c) findings.

`--check` compares the committed data with a fresh derivation and fails on any
difference (hash drift, an added or ineligible file, a label pair not derived
from its file); `tests/test_release_candidate_scan.py` runs it.

Usage:
  python3 tools/release/generate_provenance_scope.py           # write
  python3 tools/release/generate_provenance_scope.py --check   # compare
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RELEASE = Path(__file__).resolve().parent
SCOPE_PATH = "tools/release/provenance_scope.json"
SCHEMA_MANIFEST_PATH = "tools/release/schema_manifest.json"
INVENTED_STATUS = "invented_non_engineering_example"
INVENTED_FIELDS = ("origin", "source_name", "contributor_certification")
INVENTED_WORD = re.compile(r"\binvented\b", re.IGNORECASE)
PURPOSE = (
    "RT-V8 P7 (owner, 2026-10-28, as recommended): DEC-058 check (c) scope, "
    "generated by tools/release/generate_provenance_scope.py. A provenance object "
    "with violations is scoped out only when its file is listed here by path, the "
    "file's bytes hash to the listed SHA-256, and its exact (redistribution_status, "
    "review_status) JSON values are a listed pair (\"<missing>\" for an absent "
    "field). A file is listed only when one of its provenance records declares "
    "invented content (redistribution_status invented_non_engineering_example, or "
    "'invented' in origin, source_name or contributor_certification). Scoped "
    "objects are counted and named in the scan record."
)


def _load(name: str, filename: str):
    spec = importlib.util.spec_from_file_location(name, RELEASE / filename)
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault(name, module)
    spec.loader.exec_module(module)
    return module


SCAN = _load("rt_v8_scan", "run_release_candidate_scan.py")


def invented_declaration(document) -> str | None:
    """The first field by which a provenance record in `document` declares
    invented content, or None."""
    for _, record in SCAN.iter_provenance_records(document):
        if record.get("redistribution_status") == INVENTED_STATUS:
            return f"redistribution_status={INVENTED_STATUS}"
        for field in INVENTED_FIELDS:
            value = record.get(field)
            if isinstance(value, str) and INVENTED_WORD.search(value):
                return field
    return None


def scope_entry(root: Path, relative: str, schema_manifest: dict) -> dict | None:
    """The scope entry for one JSON member, or None when it has no flagged
    record or does not declare invented provenance."""
    path = root / relative
    data = path.read_bytes()
    try:
        document = json.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError):
        return None
    in_schema = SCAN.is_trusted_schema(relative, path, schema_manifest)
    labels = {
        SCAN.label_pair(record)
        for json_path, record in SCAN.iter_provenance_records(document, in_schema=in_schema)
        if SCAN.provenance_record_violations(json_path, record)
    }
    if not labels:
        return None
    declaration = invented_declaration(document)
    if declaration is None:
        return None
    return {
        "path": relative,
        "sha256": hashlib.sha256(data).hexdigest(),
        "labels": sorted(list(pair) for pair in labels),
        "reason": f"declares invented provenance ({declaration})",
    }


def build_scope(root: Path, members: list[str]) -> dict:
    schema_manifest = SCAN.load_schema_manifest(root / SCHEMA_MANIFEST_PATH)
    entries = [entry for relative in sorted(members)
               if (entry := scope_entry(root, relative, schema_manifest)) is not None]
    return {"purpose": PURPOSE, "members": entries}


def shipped_json_members(root: Path) -> list[str]:
    """The JSON files the public export selects from `root`."""
    export = _load("rt_v8_export", "export_public_openpipestress.py")
    selected, _, _ = export.select_files(root)
    return [rel.as_posix() for rel in selected if rel.suffix.lower() == ".json"]


def render(document: dict) -> str:
    return json.dumps(document, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Compare with the committed data.")
    parser.add_argument("--root", type=Path, default=ROOT, help="Project root.")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    expected = render(build_scope(root, shipped_json_members(root)))
    target = root / SCOPE_PATH
    if args.check:
        actual = target.read_text(encoding="utf-8") if target.is_file() else ""
        if actual != expected:
            print(f"{SCOPE_PATH} differs from the derivation; run generate_provenance_scope.py",
                  file=sys.stderr)
            return 1
        print(f"{SCOPE_PATH} matches {len(json.loads(expected)['members'])} files.")
        return 0
    target.write_text(expected, encoding="utf-8")
    print(f"wrote {SCOPE_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
