def cited_files():
    """The files the table cites, under the web root, sorted; the judge is read too."""
    return sorted({r['rel'] for r in ROWS})


class Check:
    def __init__(self, root: Path):
        self.web = root / WEB
        self.problems: list[str] = []
        self.digests: dict[str, dict[str, str]] = {}
        self.counts = {'declarations': 0, 'inline anchors': 0}
        self._lines: dict[str, list[str] | None] = {}

    def problem(self, text):
        self.problems.append(text)

    def lines_of(self, rel):
        if rel not in self._lines:
            path = self.web / rel
            self._lines[rel] = path.read_text(encoding='utf-8').split('\n') if path.is_file() else None
        return self._lines[rel]

    def declaration(self, predicate, rel, name):
        """(start, end, exported), 0-based and inclusive, or None with a problem naming the row."""
        src = self.lines_of(rel)
        pattern = re.compile(r'^(export\s+)?(?:async\s+)?(?:function|const|class)\s+' + re.escape(name) + r'\b')
        found = [i for i, line in enumerate(src) if pattern.match(line)]
        if len(found) != 1:
            self.problem(f'{predicate}: {len(found)} declarations of {name} in {WEB}/{rel}, expected 1')
            return None
        start = found[0]
        exported = bool(pattern.match(src[start]).group(1))
        if re.match(r'^(export\s+)?(?:async\s+)?(?:function|class)\s', src[start]):
            # A signature's own braces (a destructured parameter) do not end it; column 0 does.
            ends = [i for i in range(start, len(src)) if src[i].startswith('}')]
            if ends:
                return start, ends[0], exported
        else:
            depth, opened = 0, False
            for i in range(start, len(src)):
                depth += src[i].count('{') - src[i].count('}')
                opened = opened or '{' in src[i]
                if (opened and depth == 0) or (not opened and src[i].rstrip().endswith(';')):
                    return start, i, exported
        self.problem(f'{predicate}: the end of {name} in {WEB}/{rel} was not found')
        return None

    def anchor_line(self, predicate, rel, text):
        """The line holding `text`, which must occur exactly once in the file."""
        src = self.lines_of(rel)
        hits = '\n'.join(src).count(text)
        if hits != 1:
            self.problem(f'{predicate}: its anchor `{text}` occurs {hits} times in {WEB}/{rel}, expected 1')
            return None
        return next(i for i, line in enumerate(src) if text in line)

    def passage(self, predicate, rel, spec):
        """(start, end) of an inline row's passage, 0-based and inclusive, or None with a problem."""
        src = self.lines_of(rel)
        first = spec['from']
        if first.startswith('decl:'):
            found = self.declaration(predicate, rel, first[5:])
            start = found[0] if found else None
        else:
            start = self.anchor_line(predicate, rel, first)
        if start is None:
            return None
        to = spec.get('to')
        end = None
        if to is None:
            end = start
        elif to.startswith('end:'):
            found = self.declaration(predicate, rel, to[4:])
            if found is None:
                return None
            end = found[1]
        elif to.startswith('line:') or to.startswith('block'):
            text = to.split(':', 1)[1] if ':' in to else None
            at = start if text is None else next((i for i in range(start, len(src)) if text in src[i]), None)
            if at is None:
                self.problem(f'{predicate}: `{text}` was not found after its start in {WEB}/{rel}')
                return None
            if to.startswith('line:'):
                end = at
            else:
                depth, opened = 0, False
                for i in range(at, len(src)):
                    depth += src[i].count('{') - src[i].count('}')
                    opened = opened or '{' in src[i]
                    if opened and depth <= 0:
                        end = i
                        break
                if end is None:
                    self.problem(f'{predicate}: the end of the block it cites in {WEB}/{rel} was not found')
                    return None
        if end < start:
            self.problem(f'{predicate}: its passage in {WEB}/{rel} ends before it starts')
            return None
        mark = spec.get('mark')
        if mark:
            hits = '\n'.join(src[start:end + 1]).count(mark)
            if hits != 1:
                self.problem(f'{predicate}: its mark `{mark}` occurs {hits} times in its passage, expected 1')
                return None
        self.counts['inline anchors'] += 1
        return start, end

    def cite(self, predicate, rel, where, start, end):
        text = '\n'.join(self.lines_of(rel)[start:end + 1])
        self.digests[predicate] = {'source': f'{rel}: {where}',
                                   'sha256': hashlib.sha256(text.encode()).hexdigest()}

    def judge_imports(self):
        judge = self.web / JUDGE
        if not judge.is_file():
            self.problem(f'the judge {WEB}/{JUDGE} is missing')
            return '', {}
        text = judge.read_text(encoding='utf-8')
        imports: dict[str, list[tuple[str, bool]]] = {}
        for names, module in re.findall(r'import\s*\{([^}]*)\}\s*from\s*"([^"]+)"', text):
            if not module.startswith('.'):
                continue
            base = (judge.parent / module).resolve()
            target = next((p for p in (base.with_suffix('.ts'), base.with_suffix('.tsx')) if p.is_file()), None)
            for name in names.split(','):
                name = name.strip()
                if not name:
                    continue
                is_type = name.startswith('type ')
                name = name.removeprefix('type ').strip()
                imports.setdefault(name, []).append(
                    (target.relative_to(self.web.resolve()).as_posix() if target else module, is_type))
        return text, imports

    def run(self):
        judge_text, imports = self.judge_imports()

        def imported_from(name):
            return [m for m, is_type in imports.get(name, []) if not is_type]

        table = ['| predicate | source: declaration or passage | restated or imported | equal, or the difference |',
                 '|---|---|---|---|']
        for r in ROWS:
            predicate, rel, kind, claim = r['predicate'], r['rel'], r['kind'], r['claim']
            name = predicate.split(' ')[0]
            short = rel.rsplit('/', 1)[-1]
            if self.lines_of(rel) is None:
                self.problem(f'{predicate}: its cited file {WEB}/{rel} is missing')
                continue
            if kind.startswith('inline-inside:'):
                outer = kind.split(':', 1)[1]
                anchor = r['passage']['from']
                at = self.anchor_line(predicate, rel, anchor)
                if at is not None:
                    self.counts['inline anchors'] += 1
                    o = self.declaration(predicate, rel, outer)
                    if o is not None and not o[0] <= at <= o[1]:
                        self.problem(f'{predicate}: its anchor is not inside {outer} in {WEB}/{rel}')
                if imported_from(outer) != [rel]:
                    self.problem(f'{predicate}: {outer} is not imported by the judge from {rel}')
                where = f'the line holding {code(anchor)}, inside {outer}'
                table.append(f'| {predicate} | {short}: {where} | imported (inside the imported {outer}) | {r["difference"]} |')
                continue
            if kind == 'inline':
                span = self.passage(predicate, rel, r['passage'])
                if span is None:
                    continue
                self.cite(predicate, rel, describe(r['passage'], plain=True), *span)
                table.append(f'| {predicate} | {short}: {describe(r["passage"])} | restated ({claim}) | {r["difference"]} |')
                continue
            found = self.declaration(predicate, rel, name)
            if found is None:
                continue
            self.counts['declarations'] += 1
            start, end, exported = found
            if kind == 'imported':
                if not exported:
                    self.problem(f'{predicate}: the row says imported, but {WEB}/{rel} does not export it')
                if imported_from(name) != [rel]:
                    self.problem(f'{predicate}: the judge imports it from {imported_from(name)}, not {rel}')
                cell = 'imported'
            elif kind == 'restated':
                if imported_from(name):
                    self.problem(f'{predicate}: the row says restated, but the judge imports it')
                if claim.startswith('not exported') and exported:
                    self.problem(f'{predicate}: the row says not exported, but {WEB}/{rel} exports it')
                if claim.startswith('exported') and not exported:
                    self.problem(f'{predicate}: the row says exported, but {WEB}/{rel} does not export it')
                if name not in judge_text:
                    self.problem(f'{predicate}: the judge does not name what it restates')
                self.cite(predicate, rel, name, start, end)
                cell = f'restated ({claim})'
            elif kind.startswith('inside:'):
                outer = kind.split(':', 1)[1]
                o = self.declaration(predicate, rel, outer)
                if o is not None:
                    body = '\n'.join(self.lines_of(rel)[o[0]:o[1] + 1])
                    if not re.search(r'\b' + re.escape(name) + r'\(', body):
                        self.problem(f'{predicate}: {name} is not called inside {outer}')
                if imported_from(outer) != [rel]:
                    self.problem(f'{predicate}: {outer} is not imported by the judge from {rel}')
                if imported_from(name):
                    self.problem(f'{predicate}: the row says run inside {outer}, but the judge imports it directly')
                cell = f'{"exported" if exported else "not exported"}; run inside the imported {outer}'
            else:
                raise ValueError(f'{predicate}: unknown kind {kind}')
            table.append(f'| {predicate} | {short}: {code(name)} | {cell} | {r["difference"]} |')

        named = {r['predicate'].split(' ')[0] for r in ROWS}
        self.web_imports = 0
        for name, sources in sorted(imports.items()):
            for module, is_type in sources:
                if is_type or name in TYPES:
                    continue
                self.web_imports += 1
                if name not in named:
                    self.problem(f'the judge imports {name} from {module}, and no row names it')
        return PREAMBLE + '\n'.join(table) + '\n'


def code(text):
    """A Markdown code span inside a table cell."""
    return '`' + text.replace('|', '\\|') + '`'


def describe(spec, plain=False):
    """Where an inline row's passage is, in words; `plain` omits Markdown (the digests file)."""
    q = (lambda t: f'`{t}`') if plain else code
    first = spec['from']
    start = f'from the declaration of {first[5:]}' if first.startswith('decl:') else f'from {q(first)}'
    to = spec.get('to')
    if to is None:
        words = f'the line holding {q(first)}'
    elif to.startswith('end:'):
        words = f'{start} to the end of {to[4:]}'
    elif to == 'block':
        words = f'{start} to the end of its block'
    elif to.startswith('block:'):
        words = f'{start} to the end of the block opened at {q(to[6:])}'
    else:
        words = f'{start} through the line holding {q(to[5:])}'
    if spec.get('mark'):
        words += f', holding {q(spec["mark"])}'
    return words


def main(argv=None):
    parser = argparse.ArgumentParser(description='The after-worker family table: generate it, or check it.')
    parser.add_argument('root', type=Path, help='the repository root whose sources are read')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true', help='regenerate the table and the digests')
    mode.add_argument('--print', action='store_true', help='print the table')
    parser.add_argument('--table', type=Path, default=TABLE)
    parser.add_argument('--digests', type=Path, default=DIGESTS)
    args = parser.parse_args(argv)

    check = Check(args.root.resolve())
    text = check.run()
    recorded = None
    if args.digests.is_file():
        recorded = json.loads(args.digests.read_text(encoding='utf-8'))
    if args.print:
        sys.stdout.write(text)
    elif args.write:
        if not check.problems:
            for predicate, now in sorted(check.digests.items()):
                was = (recorded or {}).get(predicate)
                if was is None:
                    print(f'recorded: {predicate}: a new restated row; read it and say so', file=sys.stderr)
                elif was != now:
                    print(f'recorded: {predicate}: its cited text or anchor changed; read the row and say so', file=sys.stderr)
            for predicate in sorted(set(recorded or {}) - set(check.digests)):
                print(f'dropped: {predicate}: no longer a restated row', file=sys.stderr)
            args.table.write_text(text, encoding='utf-8')
            args.digests.write_text(json.dumps(check.digests, indent=2, sort_keys=True) + '\n', encoding='utf-8')
    else:
        if not args.table.is_file() or args.table.read_text(encoding='utf-8') != text:
            check.problem(f'{args.table.name} is not the generated table: regenerate it with --write and read the changed rows')
        if recorded is None:
            check.problem(f'{args.digests.name} is missing: the restated rows are checked against their recorded digests')
        else:
            for predicate, now in sorted(check.digests.items()):
                was = recorded.get(predicate)
                if was is None:
                    check.problem(f'{predicate}: no recorded digest for its cited text ({now["source"]})')
                elif was != now:
                    check.problem(f'{predicate}: its cited text changed ({now["source"]}): re-read the source and '
                                  'revalidate this row\'s restatement')
            for predicate in sorted(set(recorded) - set(check.digests)):
                if not any(p.startswith(predicate + ':') for p in check.problems):
                    check.problem(f'{predicate}: a recorded digest names no restated row')
    print(f'rows: {len(ROWS)}; {check.counts["declarations"]} declarations found once; '
          f'{check.counts["inline anchors"]} inline passages found by text; restated rows digested: {len(check.digests)}; '
          f'judge web imports: {check.web_imports}', file=sys.stderr)
    for p in check.problems:
        print('MISMATCH: ' + p, file=sys.stderr)
    return 1 if check.problems else 0


