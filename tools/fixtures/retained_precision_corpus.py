#!/usr/bin/env python3
"""Lossless storage for the shared retained-precision test corpus.

The DAG stores identical values once. Scalars retain their JSON number forms;
[0, refs...] denotes an array and [1, key_ref, value_ref, ...] an object. Every
reference names an earlier node. Expansion creates independent containers, so a
mutation of one occurrence cannot mutate another. This is test-fixture storage,
not a product reader or a numerical oracle.

Both historical full snapshots can be recovered byte for byte: ASCII JSON,
final newline, and the declared compact or indent-2 layout. Their independent
historical SHA pins stay on these expanded bytes. The full historical files are
also preserved by Git tag ``archive/piping-retained-corpus-20261011`` at commit
``26d0427061``. For example, recover the full 07o file with::

    git show archive/piping-retained-corpus-20261011:projects/chirality-piping/fixtures/results/retained_precision_cases_07o.json > /tmp/retained_precision_07o.full.json

To edit a definition, expand
it to a temporary full file, edit that file, then pack it again. Packing refuses
input whose bytes cannot be reproduced exactly; no case or assertion is pruned.

    python3 retained_precision_corpus.py expand definition.json full.json
    python3 retained_precision_corpus.py pack full.json definition.json

The synthetic reader-control bases are regenerated by their repository writer,
``retained_precision_synthetic_bases.py``, also reachable here; ``--check``
compares with the committed bytes and writes nothing::

    python3 retained_precision_corpus.py synthetic-bases [--check]
"""
import argparse
import importlib.util
import json
from pathlib import Path

FORMAT = "retained-precision-corpus-dag/v1"
LAYOUTS = ("compact", "indent-2")


def _bytes(document, layout):
    options = {"separators": (",", ":")} if layout == "compact" else {"indent": 2}
    return (json.dumps(document, ensure_ascii=True, allow_nan=False, **options) + "\n").encode()


def _definition(document):
    if not isinstance(document, dict) or set(document) != {"format", "layout", "nodes", "root"} or document["format"] != FORMAT:
        raise ValueError("unsupported retained-precision corpus storage format")
    if document["layout"] not in LAYOUTS or not isinstance(document["nodes"], list):
        raise ValueError("invalid corpus layout or nodes")
    nodes = document["nodes"]
    root = document["root"]
    if type(root) is not int or not 0 <= root < len(nodes):
        raise ValueError("invalid corpus root")
    for index, node in enumerate(nodes):
        if not isinstance(node, list):
            if isinstance(node, dict):
                raise ValueError("a corpus node is a scalar or a tagged array")
            continue
        if not node or type(node[0]) is not int or node[0] not in (0, 1):
            raise ValueError("invalid corpus node tag")
        if any(type(ref) is not int or not 0 <= ref < index for ref in node[1:]):
            raise ValueError("corpus references must name earlier nodes")
        if node[0] == 1:
            if len(node) % 2 != 1:
                raise ValueError("object nodes contain key/value pairs")
            keys = [nodes[ref] for ref in node[1::2]]
            if any(not isinstance(key, str) for key in keys) or len(set(keys)) != len(keys):
                raise ValueError("object keys must be distinct strings")
    return nodes, root


def expand(document):
    """Expand the current versioned storage definition into independent containers."""
    nodes, root = _definition(document)

    def value(index):
        node = nodes[index]
        if not isinstance(node, list):
            return node
        if node[0] == 0:
            return [value(ref) for ref in node[1:]]
        return {nodes[node[i]]: value(node[i + 1]) for i in range(1, len(node), 2)}

    return value(root)


def expanded_bytes(document):
    """Recover the exact full snapshot serialization declared by a definition."""
    _definition(document)
    return _bytes(expand(document), document["layout"])


def compact(source_bytes):
    """Intern identical values, accepting only exactly reversible source bytes."""
    original = json.loads(source_bytes)
    layout = next((name for name in LAYOUTS if _bytes(original, name) == source_bytes), None)
    if layout is None:
        raise ValueError("source bytes are not an exact supported corpus serialization")
    nodes, known = [], {}

    def intern(value):
        if isinstance(value, dict):
            node = [1, *[part for key, item in value.items() for part in (intern(key), intern(item))]]
        elif isinstance(value, list):
            node = [0, *[intern(item) for item in value]]
        else:
            node = value
        key = json.dumps(node, separators=(",", ":"), ensure_ascii=True, allow_nan=False)
        if key not in known:
            known[key] = len(nodes)
            nodes.append(node)
        return known[key]

    root = intern(original)
    definition = {"format": FORMAT, "layout": layout, "nodes": nodes, "root": root}
    if expanded_bytes(definition) != source_bytes:
        raise ValueError("corpus compaction did not preserve source bytes")
    return definition


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    operations = parser.add_subparsers(dest="operation", required=True)
    for name in ("pack", "expand"):
        operation = operations.add_parser(name)
        operation.add_argument("source", type=Path)
        operation.add_argument("destination", type=Path)
    synthetic = operations.add_parser("synthetic-bases", help="regenerate the synthetic reader-control bases")
    synthetic.add_argument("--check", action="store_true", help="compare with the committed bytes; write nothing")
    args = parser.parse_args(argv)
    if args.operation == "synthetic-bases":
        spec = importlib.util.spec_from_file_location("retained_precision_synthetic_bases", Path(__file__).with_name("retained_precision_synthetic_bases.py"))
        writer = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(writer)
        return writer.run(check=args.check)
    if args.operation == "pack":
        definition = compact(args.source.read_bytes())
        output = (json.dumps(definition, separators=(",", ":"), ensure_ascii=True, allow_nan=False) + "\n").encode()
    else:
        output = expanded_bytes(json.loads(args.source.read_bytes()))
    args.destination.write_bytes(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
