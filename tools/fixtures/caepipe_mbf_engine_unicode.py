#!/usr/bin/env python3
"""Unicode tables of the MBF engine crate (DEL-17-04 Design `desktop-mbf-export-import.md` §2).

The Rust port of the MBF importer (`core/handoff/caepipe_mbf_engine`) reproduces three Python string behaviours the
importer's outputs depend on: `str.isprintable` (which characters `repr` writes as themselves), the regular
expression class `\\d` with `int()`'s digit values (layout node numbers and English lengths), and `str.isspace`,
which `str.strip` and the class `\\s` use. This writer derives each table from the running Python and writes
`src/unicode_tables.rs`; `--check` compares and writes nothing. The tables follow the Unicode version of the Python
that writes them (recorded in the file).

Usage:
    python3 tools/fixtures/caepipe_mbf_engine_unicode.py            # write the table module
    python3 tools/fixtures/caepipe_mbf_engine_unicode.py --check    # compare, write nothing
"""
from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[2]
TARGET = PROJECT / "core/handoff/caepipe_mbf_engine/src/unicode_tables.rs"
_DIGIT = re.compile(r"\d")
_SPACE = re.compile(r"\s")


def ranges(predicate) -> list[tuple[int, int]]:
    found: list[tuple[int, int]] = []
    start = None
    for code in range(0x110000 + 1):
        inside = code <= 0x10FFFF and predicate(code)
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            found.append((start, code - 1))
            start = None
    return found


def digit_ranges() -> list[tuple[int, int, int]]:
    """(first, last, value of first): runs of `\\d` characters whose int() value rises by one per code point."""
    runs: list[tuple[int, int, int]] = []
    for code in range(0x110000):
        char = chr(code)
        if not _DIGIT.match(char):
            continue
        value = int(char)
        if char.isdecimal() is False or unicodedata.decimal(char) != value:
            raise SystemExit(f"U+{code:04X}: \\d and int() disagree with the decimal property")
        if runs and runs[-1][1] == code - 1 and runs[-1][2] + (code - runs[-1][0]) == value:
            runs[-1] = (runs[-1][0], code, runs[-1][2])
        else:
            runs.append((code, code, value))
    return runs


def render() -> str:
    for code in range(0x110000):
        char = chr(code)
        if bool(_SPACE.match(char)) != char.isspace():
            raise SystemExit(f"U+{code:04X}: \\s and str.isspace disagree")
    nonprintable = ranges(lambda code: code >= 0x80 and not chr(code).isprintable())
    digits = digit_ranges()
    spaces = [code for code in range(0x110000) if chr(code).isspace()]
    lines = [
        "// @generated by tools/fixtures/caepipe_mbf_engine_unicode.py; do not edit.",
        f"// Python {sys.version_info.major}.{sys.version_info.minor}, Unicode {unicodedata.unidata_version}.",
        "",
        "/// Code points from U+0080 on that Python's `str.isprintable` rejects, as inclusive ranges.",
        "pub(crate) const NONPRINTABLE: &[(u32, u32)] = &[",
        *(f"    (0x{low:X}, 0x{high:X})," for low, high in nonprintable),
        "];",
        "",
        "/// Python's `\\d` characters as (first, last, int() value of first), each run rising by one.",
        "pub(crate) const DECIMAL_DIGITS: &[(u32, u32, u32)] = &[",
        *(f"    (0x{low:X}, 0x{high:X}, {value})," for low, high, value in digits),
        "];",
        "",
        "/// Python's `str.isspace` (and `\\s`) characters.",
        "pub(crate) const PY_SPACE: &[u32] = &[",
        *(f"    0x{code:X}," for code in spaces),
        "];",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET.relative_to(PROJECT)} is stale; run {Path(__file__).relative_to(PROJECT)}", file=sys.stderr)
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
