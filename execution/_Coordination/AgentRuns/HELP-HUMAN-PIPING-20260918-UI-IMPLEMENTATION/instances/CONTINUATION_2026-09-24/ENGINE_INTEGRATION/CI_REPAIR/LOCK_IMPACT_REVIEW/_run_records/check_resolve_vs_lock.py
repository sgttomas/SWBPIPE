#!/usr/bin/env python3
"""Check 2: every lock entry of the four repaired lockfiles is in Cargo's resolve
of the crate's 5b1c manifest graph and vice versa, with the dependency chain that
requires each added entry; plus an independent reproduction of the repair.

Part 1 reads the `cargo metadata --locked` outputs recorded by run_cargo_checks.py
(stage meta) and compares resolve nodes/edges with the committed lock at 5b1c.
Part 2 (reproduction) works in the scratch export made by
check_src_tauri_resolve.py: each of the four locks is reset to its e650 bytes and
`cargo +1.97.1 metadata --format-version 1` is run WITHOUT --locked (the same
minimal update Cargo performs), once --offline (local cache) and once online
(crates.io index), each from a fresh copy; the regenerated bytes are compared
with the committed 5b1c lock.

Usage: python3 check_resolve_vs_lock.py <repo_root> <out_dir> <meta_dir> <scratch_root>
"""
import hashlib
import json
import os
import subprocess
import sys
import tomllib
from collections import deque
from pathlib import Path

root, out, meta_dir, scratch = (Path(x) for x in sys.argv[1:5])
OLD, NEW = 'e65001ad50072d3399bf204da02055b0f360353a', '5b1ccd356c0d9656f7b9f42c6558f7a4c73f9295'
P = 'projects/chirality-piping'
CRATES = {'report_package': 'core/reporting/report_package', 'mechanics': 'validation/benchmarks/mechanics',
          'numerical_integrity': 'validation/benchmarks/numerical_integrity', 'stress': 'validation/benchmarks/stress'}


def pkgkey_from_id(pid, packages):
    p = packages[pid]
    src = p['source']
    return (p['name'], p['version'], src)


res = {}
for crate, d in CRATES.items():
    meta = json.loads((meta_dir / f'{crate}.metadata.json').read_text())
    packages = {p['id']: p for p in meta['packages']}
    nodes = {n['id']: n for n in meta['resolve']['nodes']}
    lock_new = tomllib.loads(subprocess.check_output(['git', 'show', f'{NEW}:{P}/{d}/Cargo.lock'], cwd=root).decode())
    lock_old = tomllib.loads(subprocess.check_output(['git', 'show', f'{OLD}:{P}/{d}/Cargo.lock'], cwd=root).decode())
    lock_keys = {(p['name'], p['version'], p.get('source')) for p in lock_new['package']}
    old_keys = {(p['name'], p['version'], p.get('source')) for p in lock_old['package']}
    resolve_keys = {pkgkey_from_id(i, packages) for i in nodes}
    # Lock edges vs resolve edges (by name, names are unique in these locks)
    lock_edges = {(p['name'], dep.split(' ')[0]) for p in lock_new['package'] for dep in p.get('dependencies', [])}
    resolve_edges = {(packages[i]['name'], packages[dd['pkg']]['name']) for i, n in nodes.items() for dd in n['deps']}
    # Chain from the root to each added package, with dependency kinds
    root_id = meta['resolve']['root']
    parent = {root_id: None}
    q = deque([root_id])
    while q:
        cur = q.popleft()
        for dd in nodes[cur]['deps']:
            if dd['pkg'] not in parent:
                parent[dd['pkg']] = (cur, [k.get('kind') or 'normal' for k in dd['dep_kinds']])
                q.append(dd['pkg'])
    chains = {}
    for i in nodes:
        k = pkgkey_from_id(i, packages)
        if k not in old_keys:
            chain, cur = [], i
            while parent[cur] is not None:
                prev, kinds = parent[cur]
                chain.append(f"{packages[cur]['name']}[{'/'.join(kinds)}]")
                cur = prev
            chains[f'{k[0]} {k[1]}'] = ' <- '.join(chain + [packages[root_id]['name']])
    res[crate] = dict(lock_packages=len(lock_keys), resolve_nodes=len(resolve_keys),
                      lock_equals_resolve_packages=lock_keys == resolve_keys,
                      in_lock_not_resolve=sorted(map(str, lock_keys - resolve_keys)),
                      in_resolve_not_lock=sorted(map(str, resolve_keys - lock_keys)),
                      lock_edges_equal_resolve_edges=lock_edges == resolve_edges,
                      added_entry_chains=chains)

# Part 2: reproduction from the e650 locks in the scratch export
sp = scratch / P
env = os.environ.copy()
for k in ('CARGO_NET_OFFLINE', 'CARGO_TARGET_DIR'):
    env.pop(k, None)
env.update(CARGO_TERM_COLOR='never', CARGO_TARGET_DIR=str(scratch.parent / '_nobuild'))
repro = {}
for mode in ('offline', 'online'):
    for crate, d in CRATES.items():
        lock = sp / d / 'Cargo.lock'
        old = subprocess.check_output(['git', 'show', f'{OLD}:{P}/{d}/Cargo.lock'], cwd=root)
        new = subprocess.check_output(['git', 'show', f'{NEW}:{P}/{d}/Cargo.lock'], cwd=root)
        lock.write_bytes(old)
        args = ['cargo', '+1.97.1', 'metadata', '--format-version', '1', '--manifest-path', f'{d}/Cargo.toml']
        if mode == 'offline':
            args.insert(3, '--offline')
        r = subprocess.run(args, cwd=sp, env=env, capture_output=True, text=True)
        (out / f'repro-{mode}-{crate}.stderr.log').write_text(r.stderr)
        regenerated = lock.read_bytes()
        (out / f'repro-{mode}-{crate}.Cargo.lock').write_bytes(regenerated)
        repro[f'{mode}/{crate}'] = dict(exit_code=r.returncode, regenerated_sha256=hashlib.sha256(regenerated).hexdigest(),
                                        committed_5b1c_sha256=hashlib.sha256(new).hexdigest(),
                                        byte_identical_to_5b1c=regenerated == new,
                                        cargo_messages=[l.strip() for l in r.stderr.splitlines() if l.strip()])
        lock.write_bytes(new)  # restore scratch copy to 5b1c bytes
res['reproduction_from_e650'] = repro
(out / 'RESOLVE_VS_LOCK.json').write_text(json.dumps(res, indent=2) + '\n')
for crate in CRATES:
    r = res[crate]
    print(crate, r['lock_packages'], r['resolve_nodes'], r['lock_equals_resolve_packages'], r['lock_edges_equal_resolve_edges'])
    for k, v in r['added_entry_chains'].items():
        print('   ', k, ':', v)
for k, v in repro.items():
    print(k, v['exit_code'], v['byte_identical_to_5b1c'], v['cargo_messages'][:14])
