import json
import re
import subprocess
from pathlib import Path

import pytest

from tests.retained_precision_corpus import _STORAGE

PROJECT = Path(__file__).resolve().parents[1]
REPOSITORY = PROJECT.parents[1]
BASE = "3826a6288173928ed32a554552fec72eb8ff3dd2"

# The minimal old -> new segments of §3.3's three whole strings (the rest of
# each string is unchanged); the whole strings are pinned in
# `pressure_source_context_tests.rs`.
SEGMENTS = (
    (
        "The selected retained-source response is Euler-Bernoulli with coincident section bases.",
        "The selected retained-source response uses the contract's shear model and publishes its stress rows on both section bases.",
    ),
    (
        "carries a selected retained-source response; the selected response is euler_bernoulli with zero mill tolerance and zero corrosion allowance, where the two bases coincide. The source",
        "carries a selected retained-source response. The source",
    ),
    (
        "is available only for euler_bernoulli documents with zero mill tolerance and zero corrosion allowance, and only for straight",
        "is available only for straight",
    ),
    (
        "Timoshenko documents, nonzero mill tolerance or corrosion allowance and other source families are declined by name.",
        "Other source families are declined by name.",
    ),
)
HASH = re.compile(r"^(sha256:)?[0-9a-f]{64}$")


class Token(str):
    """A JSON number's exact source token."""


def _parse(text: str):
    return json.loads(text, parse_float=Token, parse_int=Token, object_pairs_hook=list)


def _restate(text: str) -> str:
    for old, new in SEGMENTS:
        text = text.replace(old, new)
    return text


def _embedded(text: str):
    if text[:1] in "{[":
        try:
            return _parse(text)
        except ValueError:
            return None
    return None


def _path(path: tuple) -> str:
    return "/" + "/".join("*" if isinstance(p, int) else str(p) for p in path)


def classify(base, current, path=(), out=None):
    """Every differing leaf as (class, path); class 'text', 'hash' or 'other'."""
    out = [] if out is None else out
    if isinstance(base, list) and isinstance(current, list):
        pairs = all(isinstance(x, tuple) for x in base + current)
        if pairs:  # an object, as ordered (key, value) pairs
            if [k for k, _ in base] != [k for k, _ in current]:
                out.append(("other", _path(path) + " (members)"))
                return out
            for (key, x), (_, y) in zip(base, current):
                classify(x, y, path + (key,), out)
            return out
        if len(base) != len(current):
            out.append(("other", _path(path) + " (length)"))
            return out
        for index, (x, y) in enumerate(zip(base, current)):
            classify(x, y, path + (index,), out)
        return out
    if isinstance(base, tuple) and isinstance(current, tuple):
        if base[0] != current[0]:
            out.append(("other", _path(path) + " (key)"))
        else:
            classify(base[1], current[1], path, out)
        return out
    if type(base) is not type(current):
        out.append(("other", _path(path) + " (type)"))
    elif isinstance(base, str) and base != current:
        if _restate(base) == current and not isinstance(base, Token):
            out.append(("text", _path(path)))
        elif HASH.match(base) and HASH.match(current):
            out.append(("hash", _path(path)))
        else:
            inner = (_embedded(base), _embedded(current))
            if inner[0] is not None and inner[1] is not None:
                classify(inner[0], inner[1], path + ("<json>",), out)
            else:
                out.append(("other", _path(path)))
    elif base != current:
        out.append(("other", _path(path)))
    return out


def _as_pairs(value):
    """Expanded DAG values as the ordered-pair form of `_parse`."""
    if isinstance(value, dict):
        return [(k, _as_pairs(v)) for k, v in value.items()]
    if isinstance(value, list):
        return [_as_pairs(v) for v in value]
    if isinstance(value, bool) or value is None:
        return value
    if isinstance(value, (int, float)):
        return Token(json.dumps(value))
    return value


def load(text: str):
    document = json.loads(text)
    if isinstance(document, dict) and str(document.get("format", "")).startswith("retained-precision-corpus-dag/"):
        return _as_pairs(_STORAGE.expand(document))
    return _parse(text)


def base_text(name: str) -> str:
    return subprocess.run(
        ["git", "show", f"{BASE}:projects/chirality-piping/{name}"],
        cwd=REPOSITORY, check=True, capture_output=True, text=True,
    ).stdout


def diff(name: str, base: str | None = None, current: str | None = None):
    base = base_text(name) if base is None else base
    current = (PROJECT / name).read_text() if current is None else current
    return classify(load(base), load(current))


def _summary(found):
    counts = {}
    for kind, path in found:
        counts.setdefault(kind, {}).setdefault(path, 0)
        counts[kind][path] += 1
    return counts


def check(name: str, allowed_hashes=None, base=None, current=None):
    """The file's differences, asserting the text-only rule."""
    found = diff(name, base, current)
    other = [path for kind, path in found if kind == "other"]
    assert not other, f"{name}: differs beyond the limitation text and its hashes: {other[:12]}"
    assert any(kind == "text" for kind, _ in found) or allowed_hashes is not None, (
        f"{name}: no limitation string moved (not a regenerated carrier)"
    )
    if allowed_hashes is not None:
        moved = {path.rsplit("/", 1)[-1] for kind, path in found if kind == "hash"}
        assert moved <= set(allowed_hashes), f"{name}: hashes outside {sorted(allowed_hashes)} moved: {sorted(moved)}"
    return _summary(found)


