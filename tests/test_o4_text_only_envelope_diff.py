"""O4 §4.9: `o4_text_only_envelope_diff`.

DEL-04-08 Design `o4-source-extension.md` §3.3 restates three limitation
strings (pressure-source-1 limitation 0, and limitation 7 selected and
unselected). Every committed envelope of an Euler-Bernoulli, zero-allowance
document that carries them is regenerated by its own writer. This check
compares each such regenerated file with its bytes at main `3826a62881` (the
pre-O4 base) and requires that they differ only in those strings and the
hashes that bind them (plus the DEF-E-bound hashes the route-E successors
moved under the E14 precedent): no number token, row, class, first cause,
selection or work counter differs, and no member or array element is added
or removed (§6, "A regenerated envelope differs beyond the limitation text").

J7's census pins are held to AC-002 in the owner's text of 2026-10-19: only
`envelope_sha256` may move; `results_sha256`, `summary_sha256` and
`public.identity` may not (§3.6).

The base bytes are read from Git history (the hosted workflows check out with
full history). The check is bound to O4's regeneration: a later change to a
listed file restates its own base here.
"""
