PROJECT = Path(__file__).resolve().parents[1]
REPOSITORY = PROJECT
BASE = "9e03991d392f07b578f9fac4e5e39d8d289580ea"
# Model document 0.7.0 (W-13 S1b) regenerated these files again (version token and the digests
# binding it) on top of main 116149085a; R-A's check reads each there, before that regeneration.
S1B_BASE = "116149085a523678cc8247b81e9c367bd08d4dcc"

# Counted-work leaves, by (parent key, key): a case's or the census's method
# work, and the invocation ledger. Limits are deliberately absent.
COUNTERS = frozenset({
    ("work", "charged"),
    ("work", "rejected"),
    ("invocation_work", "charged"),
    ("invocation_work", "publication_charged"),
    ("rejected_reservation", "amount"),
})
# The only text that prints work: the selected diagnostic's method summary.
WORK_TEXT = re.compile(r"(WorkReport \{ charged: )[0-9]+(, rejected: )[0-9]+")
HASH = re.compile(r"^(sha256:)?[0-9a-f]{64}$")
INTEGER = re.compile(r"^[0-9]+$")

# The hashes that bind the moved work, named per record (a `value` leaf is
# named by its parent key). `response_digest` is never among them.
RECEIPT_HASHES = frozenset({"publication_sha256", "receipt_sha256"})
DOCUMENT_HASHES = RECEIPT_HASHES | {
    "derivative_hash", "raw_source_hashes", "original_producer_checksum", "received_carrier_checksum",
}
ANALYSIS_RUN_HASHES = RECEIPT_HASHES | {"hashes"}
STRESS_NEUTRAL_HASHES = RECEIPT_HASHES | {
    "received_source_checksums", "checksum", "checksums", "package_checksum", "source_carrier_checksum",
}
J7_HASHES = frozenset({"envelope_sha256", "diagnostics_sha256"})
assert all("response_digest" not in names for names in (DOCUMENT_HASHES, ANALYSIS_RUN_HASHES, STRESS_NEUTRAL_HASHES, J7_HASHES))


class Token(str):
    """A JSON number's exact source token."""


class Obj(list):
    """A JSON object, as its ordered (key, value) pairs; distinct from an array, so
    `{}` and `[]` never compare equal (Codex review, round 2)."""


def _parse(text: str):
    return json.loads(text, parse_float=Token, parse_int=Token, object_pairs_hook=Obj)


def _expand_tokens(document):
    """A storage DAG expanded with every number's source token kept (Codex review,
    round 2: expanding parsed binary64 values let a changed token that rounds alike
    pass). `document` is the DAG parsed by `_parse`; its structure was validated by
    the storage definition's own expansion."""
    nodes = dict(document)["nodes"]

    def value(index):
        node = nodes[index]
        if not isinstance(node, list):
            return node
        if int(node[0]) == 0:
            return [value(int(ref)) for ref in node[1:]]
        return Obj((nodes[int(node[i])], value(int(node[i + 1]))) for i in range(1, len(node), 2))

    return value(int(dict(document)["root"]))


def load(text: str):
    document = json.loads(text)
    if isinstance(document, dict) and str(document.get("format", "")).startswith("retained-precision-corpus-dag/"):
        _STORAGE.expand(document)
        return _expand_tokens(_parse(text))
    return _parse(text)


def _keys(path: tuple) -> list:
    return [p for p in path if not isinstance(p, int)]


def _path(path: tuple) -> str:
    return "/" + "/".join("*" if isinstance(p, int) else str(p) for p in path)


def _mask(text: str) -> str:
    return WORK_TEXT.sub(r"\1#\2#", text)


def classify(base, current, path=(), out=None):
    """Every differing leaf as (class, path, name); class 'counter', 'text', 'hash' or 'other'."""
    out = [] if out is None else out
    if isinstance(base, list) and isinstance(current, list) and isinstance(base, Obj) != isinstance(current, Obj):
        out.append(("other", _path(path) + " (object/array)", None))
        return out
    if isinstance(base, list) and isinstance(current, list):
        if isinstance(base, Obj):  # an object, as ordered pairs
            if [k for k, _ in base] != [k for k, _ in current]:
                out.append(("other", _path(path) + " (members)", None))
                return out
            for (key, x), (_, y) in zip(base, current):
                classify(x, y, path + (key,), out)
            return out
        if len(base) != len(current):
            out.append(("other", _path(path) + " (length)", None))
            return out
        for index, (x, y) in enumerate(zip(base, current)):
            classify(x, y, path + (index,), out)
        return out
    if type(base) is not type(current):
        out.append(("other", _path(path) + " (type)", None))
    elif base == current:
        pass
    elif isinstance(base, Token):
        keys = tuple(_keys(path)[-2:])
        if keys in COUNTERS and INTEGER.match(base) and INTEGER.match(current):
            out.append(("counter", _path(path), keys))
        else:
            out.append(("other", _path(path), None))
    elif isinstance(base, str):
        keys = _keys(path)
        name = (keys[-2] if len(keys) > 1 and keys[-1] == "value" else keys[-1]) if keys else None
        if HASH.match(base) and HASH.match(current):
            out.append(("hash", _path(path), name))
        elif _mask(base) == _mask(current):
            out.append(("text", _path(path), None))
        else:
            out.append(("other", _path(path), None))
    else:
        out.append(("other", _path(path), None))
    return out


def base_text(name: str) -> str:
    return subprocess.run(
        ["git", "show", _source_spec(PROJECT, BASE, name)],
        cwd=REPOSITORY, check=True, capture_output=True, text=True,
    ).stdout


def s1b_base_text(name: str) -> str:
    """A file's bytes at the S1b base, before model document 0.7.0 regenerated it."""
    return subprocess.run(
        ["git", "show", _source_spec(PROJECT, S1B_BASE, name)],
        cwd=REPOSITORY, check=True, capture_output=True, text=True,
    ).stdout


def diff(name: str, base: str | None = None, current: str | None = None):
    base = base_text(name) if base is None else base
    current = s1b_base_text(name) if current is None else current
    return classify(load(base), load(current))


def check(name: str, hashes, base=None, current=None, found=None):
    """The file's differences, asserting the work-only rule; returns their summary."""
    found = diff(name, base, current) if found is None else found
    other = [path for kind, path, _ in found if kind == "other"]
    assert not other, f"{name}: differs beyond counted work, its printed text and binding hashes: {other[:12]}"
    stray = sorted({n for kind, _, n in found if kind == "hash"} - set(hashes))
    assert not stray, f"{name}: hashes outside {sorted(hashes)} moved: {stray}"
    return Counter((kind, re.sub(r"/\*", "/#", path)) for kind, path, _ in found)


def _moved_work(summary) -> bool:
    return any(kind == "counter" for kind, _ in summary)


