"""R-A §4: `work_only_envelope_diff`.

DEL-04-08 Design `source-work-nondyadic-inputs.md` §3.1 and §4: R-A (B1, the
negated section rows; B2, the zero-prescribed recipes) changes counted work
only. Every committed record that carries that work is regenerated by its own
writer. This check compares each regenerated file with its bytes at main
`9e03991d39` (the pre-R-A base) and requires that they differ only in

- named counted-work leaves (`COUNTERS`), each still a non-negative integer;
- the selected diagnostic text that prints the method work, compared after
  masking only the digits of its `WorkReport { charged: N, rejected: N`;
- 64-hex hashes under the keys named for each record that bind those.

No other number token (a value, interval, bound or limit), row, class, first
cause, selection or `response_digest` may differ, and no member or array
element may be added or removed. Every listed file must actually move a work
counter, so the check stays bound to the regeneration.

J7's census pins follow §4 exactly: the 66 directly selected entries move in
their method work, only the 4 `selected_published` entries (RF-SKEW
PIN-OFF-345 r1e-08 and r1e-12, both modes) also move `envelope_sha256` and
`diagnostics_sha256`, and every other entry is unchanged. `results_sha256`,
`summary_sha256` and `public.identity` do not move.

The base bytes are read from Git history (the hosted workflows check out with
full history). The check is bound to R-A's regeneration: a later change to a
listed file restates its own base here.
"""
