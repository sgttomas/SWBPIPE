"""DEL-05-01 (issue 450 item 4): the Python package reader of an exact case's ``equivalent_static``
record with its optional ``component_forces`` (``tests/verifiers/pressure_3.equivalent_static_record``,
the Rust ``physics_evidence::equivalent_static_record``). The reader checks the closed shape and that
each load identifier is in the record's inventory once and is the seismic component identifier formed
from the entry's own fields (case, axis, component); it claims nothing about the model.
The record below has the shape the producer writes for the valve of
``validation/references/seismic_component_weight`` under a g-factor along global X.

The model-bound check (Rust ``physics_evidence::equivalent_static_model_binding``, mirrored by
``tests/verifiers/reader_verdict.equivalent_static_component_checks``) is run on the solved envelopes
of ``fixtures/results/seismic_component_record_corpus.json`` (generated by
``core/product_physics/tests/seismic_component_weight.rs``): each forgery goes through the runner's
``read pressure`` and the Python mirror, which refuse it with the same code."""
import copy
import json
from pathlib import Path

import pytest

from core.analysis_runs import rust_reader
from tests.verifiers import reader_verdict as py
from tests.verifiers.pressure_3 import equivalent_static_record

CASE = "case:s"
PREFIX = f"{CASE}:generated:seismic:global-x:component:15:component:valve"
FORCE, MY, MZ = f"{PREFIX}:force", f"{PREFIX}:moment:y", f"{PREFIX}:moment:z"


def bits(value: float) -> str:
    import struct
    return struct.pack(">d", value).hex()


def record() -> dict:
    return {
        "mass_method": "source_od_nominal_wall_pressure_bore_areas/v1",
        "generated_load_ids": [f"{CASE}:generated:seismic:global-x:element-0", FORCE, MY, MZ],
        "component_forces": [{
            "component_ref": "component:valve", "node_ref": "C", "axis": "global_x",
            "g_factor": bits(0.3), "weight_N": bits(2350.0),
            "center_of_gravity_m": [bits(-0.175), bits(0.12), bits(0.125)],
            "force": {"load_id": FORCE, "value_N": bits(705.0)},
            "moments": [{"load_id": MY, "axis": "global_y", "value_N_m": bits(0.125 * 705.0)},
                        {"load_id": MZ, "axis": "global_z", "value_N_m": bits(-0.12 * 705.0)}],
        }],
    }


def test_the_record_with_and_without_component_forces_is_admitted():
    equivalent_static_record(CASE, record())
    earlier = record()
    del earlier["component_forces"]
    equivalent_static_record(CASE, earlier)


def _set(path, value):
    def edit(r):
        target = r
        for key in path[:-1]:
            target = target[key]
        target[path[-1]] = value
    return edit


def _also_in_inventory(path, value):
    """Set an identifier and list it in the inventory, so that only its form is wrong."""
    def edit(r):
        _set(path, value)(r)
        r["generated_load_ids"].append(value)
    return edit


def _wind_case(r):
    """Issue 450 round 1 finding 3: a wind-only generating case whose record carries a component entry
    naming one of its own wind primitives, with no moments. Every identifier is in the inventory."""
    wind = f"{CASE}:generated:wind:element-0"
    r["generated_load_ids"] = [wind]
    r["component_forces"][0]["force"]["load_id"] = wind
    r["component_forces"][0]["moments"] = []


@pytest.mark.parametrize("what, edit", [
    ("extra record key", _set(["extra"], 1)),
    ("empty list", _set(["component_forces"], [])),
    ("extra entry key", _set(["component_forces", 0, "extra"], 1)),
    ("decimal value", _set(["component_forces", 0, "force", "value_N"], "705")),
    ("uppercase hex", _set(["component_forces", 0, "weight_N"], bits(2350.0).upper())),
    ("two offset coordinates", _set(["component_forces", 0, "center_of_gravity_m"], [bits(0.0), bits(0.0)])),
    ("local axis", _set(["component_forces", 0, "axis"], "local_x")),
    ("moment about its own axis", _set(["component_forces", 0, "moments", 0, "axis"], "global_x")),
    ("two moments about one axis", _set(["component_forces", 0, "moments", 1, "axis"], "global_y")),
    ("id outside the inventory", _set(["component_forces", 0, "force", "load_id"], f"{CASE}:generated:seismic:global-x:other")),
    ("id twice", _set(["component_forces", 0, "moments", 1, "load_id"], MY)),
    ("force id of another axis", _also_in_inventory(["component_forces", 0, "force", "load_id"],
                                                    f"{CASE}:generated:seismic:global-y:component:15:component:valve:force")),
    ("moment id of another moment axis", _also_in_inventory(["component_forces", 0, "moments", 0, "load_id"], f"{PREFIX}:moment:x")),
    ("component length not the byte length", _also_in_inventory(["component_forces", 0, "force", "load_id"],
                                                                f"{CASE}:generated:seismic:global-x:component:14:component:valve:force")),
    ("another component's id", _also_in_inventory(["component_forces", 0, "force", "load_id"],
                                                  f"{CASE}:generated:seismic:global-x:component:16:component:flange:force")),
    ("a wind generated id with empty moments", _wind_case),
])
def test_a_malformed_component_record_is_refused(what, edit):
    forged = copy.deepcopy(record())
    edit(forged)
    with pytest.raises(ValueError, match="SOURCE_PHYSICS_EVIDENCE_INVALID: equivalent_static"):
        equivalent_static_record(CASE, forged)


def test_values_are_not_bound_to_a_model_here():
    """A changed bit is admitted by the package reader: binding to the model is the model-bound check's."""
    forged = record()
    forged["component_forces"][0]["force"]["value_N"] = bits(705.0000000000001)
    equivalent_static_record(CASE, forged)


# ----------------------------------------------------------------------------- the model-bound check, both readers
CORPUS = Path(__file__).resolve().parents[1] / "fixtures/results/seismic_component_record_corpus.json"
MISMATCH = "SOURCE_PHYSICS_EQUIVALENT_STATIC_COMPONENT_MODEL_MISMATCH"
MISSING = "SOURCE_PHYSICS_EQUIVALENT_STATIC_COMPONENT_RECORD_MISSING"
RANGE = "SOURCE_PHYSICS_EQUIVALENT_STATIC_COMPONENT_RANGE"


def _corpus(index):
    entry = json.loads(CORPUS.read_text(encoding="utf-8"))["cases"][index]
    return entry["envelope"], entry["model"]


def _codes(source, model):
    """(the runner's code, the mirror's code), None for an admitted document."""
    passed, outcome = rust_reader._run("pressure", {"source": source, "model": model})
    verdict = py.validate("pressure", source, model)
    return (None if passed else outcome["error"]["code"]), (None if verdict["ok"] else verdict["error"]["code"])


def _case(source, case_id):
    return next(c for c in source["contract_evidence"]["exact_cases"] if c["load_case_id"] == case_id)


def _entry_for(source, case_id):
    """The seismic case's first entry, re-identified for another case."""
    text = json.dumps(_case(source, "case:s")["equivalent_static"]["component_forces"][0])
    return json.loads(text.replace("case:s:generated:", f"{case_id}:generated:"))


def _ids(entry):
    return [entry["force"]["load_id"], *(m["load_id"] for m in entry["moments"])]


def _on_wind(source, model):
    record = _case(source, "case:w")["equivalent_static"]
    entry = _entry_for(source, "case:w")
    record["generated_load_ids"].extend(_ids(entry))
    record["component_forces"] = [entry]


def _on_plain(source, model):
    entry = _entry_for(source, "case:p")
    _case(source, "case:p")["equivalent_static"] = {
        "mass_method": "source_od_nominal_wall_pressure_bore_areas/v1",
        "generated_load_ids": ["case:p:generated:seismic:global-x:element-0", *_ids(entry)], "component_forces": [entry]}


def _omitted(source, model):
    del _case(source, "case:s")["equivalent_static"]["component_forces"]


def _one_bit(source, model):
    force = _case(source, "case:s")["equivalent_static"]["component_forces"][0]["force"]
    force["value_N"] = f"{int(force['value_N'], 16) + 1:016x}"


def _weight(value):
    def edit(source, model):
        model["components"][0]["geometry"]["weight"]["value"] = value
    return edit


@pytest.mark.parametrize("what, edit, expected", [
    ("a well-formed entry on the wind-only case", _on_wind, MISMATCH),
    ("a well-formed entry on the case without generation", _on_plain, MISMATCH),
    ("the required record omitted (a result saved before the unit)", _omitted, MISSING),
    ("a force one bit off", _one_bit, MISMATCH),
    ("a model whose valve does not replace (zero weight)", _weight(0.0), MISMATCH),
    ("a model whose required force rounds to zero (W the smallest positive binary64 in N)", _weight(5e-324), RANGE),
])
def test_both_model_bound_readers_refuse_each_forgery_alike(what, edit, expected):
    source, model = _corpus(0)
    assert model["components"][0]["geometry"]["weight"]["unit"] == "N"
    edit(source, model)
    assert py.validate("pressure", source)["ok"], f"{what}: the package reader claims nothing about the model"
    assert _codes(source, model) == (expected, expected), what


@pytest.mark.parametrize("index", [0, 1])
def test_both_model_bound_readers_admit_the_producer_s_records(index):
    source, model = _corpus(index)
    assert _codes(source, model) == (None, None)


def test_a_coordinate_that_converts_to_zero_is_read_after_conversion():
    """Issue 450 round 1 finding 2: 1e-321 mm converts to 0 m, and neither the producer nor either reader
    forms a moment term with it."""
    source, model = _corpus(1)
    assert model["components"][0]["geometry"]["center_of_gravity"]["y"] == 1e-321
    entries = _case(source, "case:s")["equivalent_static"]["component_forces"]
    assert [len(e["moments"]) for e in entries] == [1, 2, 1]
    assert all(e["center_of_gravity_m"][1] == "0000000000000000" for e in entries)
    assert _codes(source, model) == (None, None)
