//! The hydrostatic test case on the exact pressure route (DEL-05-01 REQ-014,
//! AC-010, VER-007; DEL-04-07 REQ-011, AC-012, VER-010), against the frozen
//! independent references of `validation/references/hydrostatic_test`.
//!
//! The oracle is `references.json`, pinned to the hash its SHA256SUMS records;
//! nothing here derives an expectation from product code. Each reference
//! document is authored from the package's inputs as a plain exact document: a
//! straight run along X, one pressure region closed by caps carried by the pipe
//! at both ends, the case's own authored pressure, and the case's self-weight
//! generated by the product's own self-weight plan (gravity along -Z) on the
//! section's own contents. A test case selects its contents from a condition
//! set (`condition_use.contents_density`), which the solve takes once into that
//! self-weight in place of the section's contents.
//!
//! Every row is compared in both solver modes. The criterion is the analytic
//! tolerance of DEL-05-01 AC-001: |obs - exp| <= 1e-9 |exp|, with an absolute
//! floor of 1e-9 times the row family's scale (w·a for forces, w·a² for
//! moments, δ₀ for displacements, p for stresses) near zero.
//!
//! Known product finding, not fitted: the product does not apply a variable
//! spring hanger's cold load (SPRING_HANGER_LOAD_NOT_APPLIED_AS_PRELOAD; its
//! entered loads are review evidence). The references apply it (DEL-04-03
//! REQ-014). The rows of the cases with an acting (not held) variable spring
//! therefore disagree and are listed in `COLD_LOAD_CASES`: the test asserts the
//! product's own warning there and compares the rows the cold load cannot
//! move (axial reaction and the Lamé stresses). Holding the variable spring
//! removes its cold load from the system, so its held cases are compared in
//! full.
use open_pipe_stress_product_physics::self_weight::{generate_self_weight_operations, SelfWeightGravity, SelfWeightRequest};
use open_pipe_stress_product_physics::{run_linear_static_preview_value_with_mode, PreviewModel, PreviewSolverMode};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;

const REFERENCES: &str = include_str!("../../../validation/references/hydrostatic_test/references.json");
const SUMS: &str = include_str!("../../../validation/references/hydrostatic_test/SHA256SUMS");
const MODES: [PreviewSolverMode; 2] = [PreviewSolverMode::SparseInteractive, PreviewSolverMode::DenseScrutiny];
const RELATIVE: f64 = 1.0e-9;
const PROV: &str = "invented hydrostatic test reference input; not library, catalog or code data";
const SET: &str = "cs:test";
const KEY: &str = "HYDRO";
/// The cases whose acting variable spring carries a cold load the product does
/// not apply (see the module comment).
const COLD_LOAD_CASES: [&str; 3] = ["HT-2S-VSPRING-NONE", "HT-4S-ORDINARY", "HT-4S-TEST-NONE"];

fn refs() -> Value {
    serde_json::from_str(REFERENCES).expect("references.json parses")
}
fn input(key: &str) -> f64 {
    refs()["inputs"][key]["value"].as_f64().unwrap_or_else(|| panic!("no input {key}"))
}
fn derived(key: &str) -> f64 {
    refs()["derived"][key]["value"].as_f64().unwrap_or_else(|| panic!("no derived {key}"))
}
fn qv(value: f64, unit: &str) -> Value {
    json!({"value": value, "unit": unit})
}

#[test]
fn references_are_the_frozen_bytes() {
    let digest: String = Sha256::digest(REFERENCES.as_bytes()).iter().map(|b| format!("{b:02x}")).collect();
    let line = SUMS.lines().find(|l| l.ends_with("  references.json")).expect("SHA256SUMS lists references.json");
    assert_eq!(&line[..64], digest);
    let doc = refs();
    assert_eq!(doc["cases"].as_array().unwrap().len(), 14);
    assert_eq!(doc["refusals"].as_array().unwrap().len(), 3);
    assert!(doc["crosscheck"].as_array().unwrap().iter().all(|c| c["agrees"] == true));
}

// ------------------------------------------------------------------ authoring

fn letter(index: usize) -> char {
    (b'a' + index as u8) as char
}

fn section() -> Value {
    json!({"outside_diameter": qv(input("D"), "m"), "wall_thickness": qv(input("t"), "m"), "mill_tolerance": qv(input("c_m"), "m"),
        "corrosion_allowance": qv(input("c_a"), "m"), "material_density": qv(input("rho_m"), "kg/m^3"),
        "contents_density": qv(input("rho_c_section"), "kg/m^3"), "insulation_thickness": qv(input("t_i"), "m"),
        "insulation_density": qv(input("rho_i"), "kg/m^3")})
}

/// The interior support of `family` at `node` with its model's inputs.
fn interior(model: &str, node: &str, support: &str, family: &str) -> Value {
    let (k, fc, fce) = match (model, node) {
        ("M2-SPRING", _) => (input("k_2s"), 0.0, 0.0),
        ("M2-VSPRING", _) => (input("kv_2s"), input("Fc_2s"), 0.0),
        ("M2-CE", _) => (0.0, 0.0, input("Fce_2s")),
        ("M4", "node:b") => (input("k_4s_b"), 0.0, 0.0),
        ("M4", "node:c") => (0.0, 0.0, input("Fce_4s_c")),
        ("M4", "node:d") => (input("kv_4s_d"), input("Fc_4s_d"), 0.0),
        other => panic!("no support inputs for {other:?}"),
    };
    match family {
        "spring" => json!({"id": support, "node": node, "family": "spring", "restraints": ["UZ"], "stiffness": {"dof": "UZ", "value": qv(k, "N/m")}, "provenance": PROV}),
        // Installed and hot loads are review metadata the record requires; they
        // carry the cold load and are never mechanics.
        "variable_spring" => json!({"id": support, "node": node, "family": "variable_spring_hanger", "restraints": ["UZ"],
            "hanger": {"hanger_type": "variable_spring_hanger", "stiffness": {"dof": "UZ", "value": qv(k, "N/m")},
                "installed_load": qv(fc, "N"), "cold_load": qv(fc, "N"), "hot_load": qv(fc, "N"), "travel_range": qv(0.05, "m"),
                "source_reference": "invented"}, "provenance": PROV}),
        "constant_effort" => json!({"id": support, "node": node, "family": "constant_effort_support", "restraints": ["UZ"],
            "hanger": {"hanger_type": "constant_effort_support", "constant_load": qv(fce, "N"), "travel_range": qv(0.05, "m"),
                "source_reference": "invented"}, "provenance": PROV}),
        other => panic!("family {other}"),
    }
}

struct Built {
    nodes: usize,
    span: f64,
}

/// The model `key` as a document with no cases: nodes, pipes (each assigned the
/// test condition set), the end supports and the interior supports.
fn skeleton(key: &str, shear_model: &str) -> (Value, Built) {
    let refs = refs();
    let spec = &refs["models"][key];
    let spans = spec["spans"].as_u64().unwrap() as usize;
    let span = input(spec["span_length_input"].as_str().unwrap());
    let nodes: Vec<Value> = (0..=spans)
        .map(|i| json!({"id": format!("node:{}", letter(i)), "position": {"x": i as f64 * span, "y": 0.0, "z": 0.0}, "provenance": PROV}))
        .collect();
    let pipes: Vec<Value> = (0..spans)
        .map(|i| json!({"id": format!("pipe:{}-{}", letter(i), letter(i + 1)), "from": format!("node:{}", letter(i)), "to": format!("node:{}", letter(i + 1)),
            "section": section(), "material": "material:ht", "condition_set_ref": SET, "y_reference": {"x": 0.0, "y": 1.0, "z": 0.0}, "provenance": PROV}))
        .collect();
    let last = letter(spans);
    let mut supports = vec![
        json!({"id": "support:a", "node": "node:a", "family": "anchor", "restraints": ["UX", "UY", "UZ", "RX"], "provenance": PROV}),
        json!({"id": format!("support:{last}"), "node": format!("node:{last}"), "family": "guide", "restraints": ["UY", "UZ"], "provenance": PROV}),
    ];
    for (node, item) in spec["interior_supports"].as_object().unwrap() {
        supports.push(interior(key, node, item["support"].as_str().unwrap(), item["family"].as_str().unwrap()));
    }
    let model = json!({"schema_version": "0.9.0", "document_kind": "openpipestress.product_preview.model",
        "pressure_contract": {"version": "3.0.0", "mode": "exact_pressure_v3", "shear_model": shear_model},
        "project": {"id": "project:hydrostatic-test", "units": {"length": "m", "force": "N", "angle": "rad", "pressure": "Pa", "stress": "Pa", "temperature": "degC"}},
        "analysis_status": {"mechanics": "ready_for_preview_diagnostics", "rule_check": "not_performed_user_rule_inputs_missing", "professional_acceptance": "not_provided"},
        "nodes": nodes, "pipe_segments": pipes, "supports": supports, "components": [],
        "materials": [{"id": "material:ht", "constitutive_basis": "homogeneous_isotropic_E_nu_v1", "elastic_modulus": qv(input("E"), "Pa"),
            "poisson_ratio": qv(input("nu"), "1"), "provenance": PROV}],
        "condition_sets": [{"id": SET, "label": "Test contents", "provenance": PROV,
            "conditions": [{"key": KEY, "contents_density": qv(input("rho_c_test"), "kg/m^3")}]}],
        "load_cases": [], "combinations": []});
    (model, Built { nodes: spans + 1, span })
}

/// The case's self-weight, generated by the product's plan for `case_id` on
/// every pipe with gravity 9.79 m/s² along -Z, as the primitives it would add.
fn self_weight(model: &Value, case_id: &str) -> Vec<Value> {
    let typed: PreviewModel = serde_json::from_value(model.clone()).expect("the skeleton decodes");
    let pipes = model["pipe_segments"].as_array().unwrap().iter().map(|p| p["id"].as_str().unwrap().to_string()).collect();
    let request = SelfWeightRequest {
        case_id: case_id.into(), label: case_id.into(), pipe_refs: pipes,
        gravity: SelfWeightGravity { value: -input("g"), unit: "m/s^2".into(), axis: "global_z".into() },
        provenance: PROV.into(), source_model_hash: format!("sha256:{}", "0".repeat(64)),
    };
    let plan = generate_self_weight_operations(&typed, &request).unwrap_or_else(|d| panic!("self-weight plan refused: {d:?}"));
    plan.changes[1..].iter().map(|change| serde_json::from_str(&change.after).unwrap()).collect()
}

/// One case of a reference document: its generated weight, its pressure region
/// over the whole run with both end caps carried by the pipe, and for a test
/// case its declaration and contents selection.
fn case_record(model: &Value, built: &Built, reference: &Value) -> Value {
    let id = reference["id"].as_str().unwrap();
    let pipes: Vec<String> = model["pipe_segments"].as_array().unwrap().iter().map(|p| p["id"].as_str().unwrap().to_string()).collect();
    let terminal = |node: String| json!({"node_ref": node, "closure_transfer": "transfers_to_wall", "provenance": PROV});
    let mut case = json!({"id": id, "label": id, "kind": "primitive_user_load", "status": "draft", "provenance": PROV,
        "primitive_loads": self_weight(model, id),
        "pressure_regions": [{"id": format!("region:{id}"), "member_pipe_ids": pipes, "pressure_basis": "internal_differential_zero_external_v1",
            "pressure": qv(reference["pressure"]["value"].as_f64().unwrap(), "Pa"),
            "terminals": [terminal("node:a".into()), terminal(format!("node:{}", letter(built.nodes - 1)))], "provenance": PROV}]});
    if !reference["test_condition"].is_null() {
        case["test_condition"] = reference["test_condition"].clone();
        case["condition_use"] = json!({"contents_density": KEY});
    }
    case
}

/// Every reference document with all of its cases, in reference order.
fn documents() -> BTreeMap<String, (Value, Built, Vec<Value>)> {
    let mut out: BTreeMap<String, (Value, Built, Vec<Value>)> = BTreeMap::new();
    for reference in refs()["cases"].as_array().unwrap() {
        let doc = reference["document"].as_str().unwrap().to_string();
        let entry = out.entry(doc).or_insert_with(|| {
            let (model, built) = skeleton(reference["model"].as_str().unwrap(), reference["shear_model"].as_str().unwrap());
            (model, built, Vec::new())
        });
        entry.2.push(reference.clone());
    }
    for (model, built, cases) in out.values_mut() {
        let records: Vec<Value> = cases.iter().map(|reference| case_record(model, built, reference)).collect();
        model["load_cases"] = json!(records);
    }
    out
}

// ------------------------------------------------------------------ running

fn run(model: &Value, mode: PreviewSolverMode) -> Value {
    let out = run_linear_static_preview_value_with_mode(json!({"model": model, "materials": []}), mode)
        .unwrap_or_else(|e| panic!("typed boundary rejected the request: {e}"));
    serde_json::to_value(out).unwrap()
}
fn codes(out: &Value) -> Vec<String> {
    out["diagnostics"].as_array().unwrap().iter().map(|d| format!("{}: {}", d["code"].as_str().unwrap(), d["message"].as_str().unwrap_or(""))).collect()
}
fn solved(model: &Value, mode: PreviewSolverMode, what: &str) -> Value {
    let out = run(model, mode);
    assert_eq!(out["status"]["mechanics"], "MECHANICS_SOLVED", "{what} {mode:?}: {:#?}",
        codes(&out).into_iter().filter(|c| !c.starts_with("NUMERICAL_INTEGRITY")).collect::<Vec<_>>());
    out
}
fn rows(out: &Value) -> &Vec<Value> {
    out["results"].as_array().expect("results")
}
fn case_rows<'a>(out: &'a Value, case_id: &'a str) -> impl Iterator<Item = &'a Value> {
    rows(out).iter().filter(move |row| row["basis_ref"]["ref_id"] == case_id)
}
fn exact_case<'a>(out: &'a Value, case_id: &str) -> &'a Value {
    out["contract_evidence"]["exact_cases"].as_array().unwrap().iter().find(|c| c["load_case_id"] == case_id)
        .unwrap_or_else(|| panic!("no exact case {case_id}"))
}

/// The published support force on the pipe along a global axis: the support's
/// reaction row, which for an acting constant-effort support already carries
/// its applied force (its applied-load row is evidence of that force, not an
/// addition to it).
fn support_force(out: &Value, case_id: &str, support: &str, component: &str) -> Option<f64> {
    let reaction: Vec<f64> = case_rows(out, case_id)
        .filter(|row| row["kind"] == "support_reaction_component_v2" && row["entity_ref"] == support && row["metadata"]["component"] == component)
        .map(si)
        .collect();
    assert!(reaction.len() <= 1, "{case_id}: {support} {component} published {} times", reaction.len());
    reaction.first().copied()
}

fn nodal_uz(out: &Value, case_id: &str, node: &str) -> f64 {
    let found: Vec<&Value> = case_rows(out, case_id).filter(|row| row["kind"] == "global_nodal_displacement_z" && row["entity_ref"] == node).collect();
    assert_eq!(found.len(), 1, "{case_id}: one uz row for {node}");
    si(found[0])
}

/// Every published Lamé row of `case_id` for (component, basis), in Pa.
fn lame(out: &Value, case_id: &str, component: &str, basis: &str) -> Vec<f64> {
    let kind = if component.contains("hoop") { "pipe_lame_hoop_stress_v2" } else { "pipe_lame_radial_stress_v2" };
    case_rows(out, case_id)
        .filter(|row| row["kind"] == kind && row["metadata"]["component"] == component
            && row["metadata"]["basis"].as_str().is_some_and(|b| b.contains(&format!("section_basis={basis}"))))
        .map(si)
        .collect()
}

/// A published row's value in SI (N, m, Pa), by the row's own unit.
fn si(row: &Value) -> f64 {
    let value = row["value"].as_f64().expect("a numeric row");
    let factor = match row["unit"].as_str().expect("a row unit") {
        "N" | "m" | "Pa" | "N*m" => 1.0,
        "kN" | "kPa" | "kN*m" => 1.0e3,
        "MPa" => 1.0e6,
        "mm" => 1.0e-3,
        other => panic!("unexpected row unit {other}"),
    };
    value * factor
}

fn close(observed: f64, expected: f64, scale: f64) -> bool {
    (observed - expected).abs() <= RELATIVE * expected.abs().max(scale)
}

/// The observed value of one reference row (`support:x.fz`, `node:b.uz`,
/// `nominal_section.hoop.bore`), or every published station for a stress row.
fn observe(out: &Value, case_id: &str, row_id: &str) -> Vec<f64> {
    if let Some((basis, rest)) = row_id.split_once("_section.") {
        let (kind, surface) = rest.split_once('.').unwrap();
        let component = format!("lame_{}_{kind}_stress", if surface == "bore" { "inner" } else { "outer" });
        let found = lame(out, case_id, &component, &format!("{basis}_section"));
        assert!(!found.is_empty(), "{case_id}: no {component} rows on {basis}");
        return found;
    }
    let (entity, component) = row_id.split_once('.').unwrap();
    if component == "uz" {
        return vec![nodal_uz(out, case_id, entity)];
    }
    let mut chars = component.chars();
    let component = format!("{}{}", chars.next().unwrap().to_ascii_uppercase(), chars.as_str());
    vec![support_force(out, case_id, entity, &component).unwrap_or(0.0)]
}

fn scale_of(reference: &Value, row: &Value, built: &Built) -> f64 {
    let w = reference["weight_per_length"]["value"].as_f64().unwrap();
    match row["unit"].as_str().unwrap() {
        "N" => w * built.span,
        "N*m" => w * built.span * built.span,
        "m" => derived("two_span_delta0_test_euler_bernoulli"),
        "Pa" => reference["pressure"]["value"].as_f64().unwrap(),
        other => panic!("unit {other}"),
    }
}

fn vertical(row_id: &str) -> bool {
    row_id.ends_with(".fz") || row_id.ends_with(".uz")
}

// ------------------------------------------------------------------ the comparison

/// Every row of every case, in both solver modes; every negative control fails;
/// the mark, the held choice and the held supports; the held constant-effort
/// support applies no force; support force and moment balance the case's own
/// weight.
#[test]
fn every_reference_case_reproduces_its_rows_in_both_modes() {
    let mut compared = 0;
    for (doc, (model, built, cases)) in documents() {
        for mode in MODES {
            let out = solved(&model, mode, &doc);
            for reference in &cases {
                let id = reference["id"].as_str().unwrap();
                let cold = COLD_LOAD_CASES.contains(&id);
                if cold {
                    assert!(out["diagnostics"].as_array().unwrap().iter().any(|d| d["code"] == "SPRING_HANGER_LOAD_NOT_APPLIED_AS_PRELOAD"),
                        "{id}: the product states that the cold load is not applied");
                }
                for row in reference["rows"].as_array().unwrap() {
                    let row_id = row["id"].as_str().unwrap();
                    if cold && vertical(row_id) {
                        continue;
                    }
                    let expected = row["value"].as_f64().unwrap();
                    let scale = scale_of(reference, row, &built);
                    for observed in observe(&out, id, row_id) {
                        assert!(close(observed, expected, scale), "{doc} {mode:?} {id} {row_id}: observed {observed:e}, expected {expected:e}");
                        compared += 1;
                    }
                }
                // Each negative control is a wrong outcome the result must not show.
                for control in reference["negative_controls"].as_array().unwrap() {
                    let differs = control["rows"].as_array().unwrap().iter().filter(|row| {
                        let row_id = row["id"].as_str().unwrap();
                        row_id != "weight_per_length" && !(cold && vertical(row_id))
                    }).any(|row| {
                        let row_id = row["id"].as_str().unwrap();
                        let scale = scale_of(reference, row, &built);
                        observe(&out, id, row_id).iter().any(|observed| !close(*observed, row["value"].as_f64().unwrap(), scale))
                    });
                    assert!(differs, "{id}: negative control {} is indistinguishable from the result", control["id"]);
                }
                mark_and_balance(&out, reference, &built, cold);
            }
        }
    }
    assert!(compared > 300, "compared {compared} values");
}

fn mark_and_balance(out: &Value, reference: &Value, built: &Built, cold: bool) {
    let id = reference["id"].as_str().unwrap();
    let expected = &reference["expected_outcome"];
    let evidence = exact_case(out, id);
    if expected["marked_hydrostatic_test"] == true {
        let mark = &evidence["test_condition"];
        assert_eq!(mark["kind"], "hydrostatic", "{id}");
        assert_eq!(mark["held_supports"], expected["held_supports_choice"], "{id}");
        assert_eq!(mark["held_support_refs"], expected["held_support_ids"], "{id}");
        assert_eq!(mark["contents_condition"], KEY, "{id}");
        let resolution = mark["contents_resolution"].as_array().unwrap();
        assert_eq!(resolution.len(), built.nodes - 1, "{id}: every pipe's self-weight takes the test contents once");
        let w = reference["weight_per_length"]["value"].as_f64().unwrap();
        for item in resolution {
            assert_eq!(item["condition_set_ref"], SET);
            assert_eq!(item["contents_density"], qv(input("rho_c_test"), "kg/m^3"));
            assert!(close(-item["applied_n_per_m"].as_f64().unwrap(), w, w), "{id}: {item}");
        }
    } else {
        assert!(evidence.get("test_condition").is_none(), "{id}: an ordinary case carries no mark");
    }
    // A held constant-effort support applies no force: no applied-load row, its
    // reaction under its own identity.
    for entry in expected["constant_effort_applied_force"].as_array().unwrap() {
        let support = entry["support"].as_str().unwrap();
        let applied: Vec<&Value> = case_rows(out, id).filter(|row| row["kind"] == "constant_effort_support_applied_load" && row["entity_ref"] == support).collect();
        if entry["applied_force"]["value"].as_f64().unwrap() == 0.0 {
            assert!(applied.is_empty(), "{id}: a held constant-effort support publishes no applied force");
        } else {
            assert_eq!(applied.len(), 1, "{id}");
            assert!(close(si(applied[0]), entry["applied_force"]["value"].as_f64().unwrap(), 1.0));
        }
    }
    if cold {
        return;
    }
    // Support force and moment balance against the case's own weight (exit
    // criterion 2): ΣF_z = w·L and Σ x·F_z = w·L²/2 about node:a.
    let w = reference["weight_per_length"]["value"].as_f64().unwrap();
    let length = built.span * (built.nodes - 1) as f64;
    let (mut force, mut moment) = (0.0, 0.0);
    for support in out_supports(out, id) {
        let fz = support_force(out, id, &support.0, "Fz").unwrap_or(0.0);
        force += fz;
        moment += support.1 * fz;
    }
    assert!(close(force, w * length, w * length), "{id}: ΣFz {force} against w·L {}", w * length);
    assert!(close(moment, w * length * length / 2.0, w * length * length), "{id}: ΣxFz {moment}");
}

/// Every support identity published in the case's rows, with its node's x.
fn out_supports(out: &Value, case_id: &str) -> Vec<(String, f64)> {
    let mut found: BTreeMap<String, f64> = BTreeMap::new();
    for row in case_rows(out, case_id).filter(|row| row["kind"] == "support_reaction_component_v2" || row["kind"] == "constant_effort_support_applied_load") {
        let support = row["entity_ref"].as_str().unwrap().to_string();
        let node = support.trim_start_matches("support:");
        let index = (node.as_bytes()[0] - b'a') as f64;
        let span = if case_id.starts_with("HT-1S") { input("L1") } else { input("a") };
        found.insert(support, index * span);
    }
    found.into_iter().collect()
}

/// The applied self-weight of a test case differs from the stored primitive by
/// exactly the contents term g·(ρ_test − ρ_section)·A_bore, and the stored
/// primitive is unchanged in the document.
#[test]
fn the_test_contents_enter_the_self_weight_once() {
    let docs = documents();
    let (model, _, _) = &docs["DOC-1S"];
    let stored = model["load_cases"].as_array().unwrap().iter().find(|c| c["id"] == "HT-1S-TEST").unwrap()["primitive_loads"][0]["magnitude"]["value"].as_f64().unwrap();
    assert!(close(-stored, derived("w_ordinary"), derived("w_ordinary")), "the stored primitive carries the section's contents: {stored}");
    for mode in MODES {
        let out = solved(model, mode, "DOC-1S");
        let applied = exact_case(&out, "HT-1S-TEST")["test_condition"]["contents_resolution"][0]["applied_n_per_m"].as_f64().unwrap();
        let term = input("g") * (input("rho_c_test") - input("rho_c_section")) * derived("A_bore");
        assert!(close(stored - applied, term, term), "{mode:?}: applied {applied}, stored {stored}, contents term {term}");
        assert!(exact_case(&out, "HT-1S-ORDINARY").get("test_condition").is_none());
    }
}

/// After save and reopen (canonical bytes, decoded again) the same input gives
/// the same result rows and mark, in both modes.
#[test]
fn the_same_input_gives_the_same_result_after_save_and_reopen() {
    let docs = documents();
    let (model, _, _) = &docs["DOC-4S"];
    let saved = serde_json::to_string(model).unwrap();
    let reopened: Value = serde_json::from_str(&saved).unwrap();
    for mode in MODES {
        let first = solved(model, mode, "DOC-4S");
        let second = solved(&reopened, mode, "DOC-4S reopened");
        assert_eq!(first["results"], second["results"], "{mode:?}");
        assert_eq!(first["contract_evidence"]["exact_cases"], second["contract_evidence"]["exact_cases"], "{mode:?}");
    }
}

// ------------------------------------------------------------------ refusals

fn refused(model: &Value, code: &str, what: &str) {
    for mode in MODES {
        let out = run(model, mode);
        assert_eq!(out["status"]["mechanics"], "MODEL_INCOMPLETE", "{what}: {:?}", codes(&out));
        assert!(rows(&out).is_empty(), "{what}: a refused document publishes no rows");
        assert!(out["diagnostics"].as_array().unwrap().iter().any(|d| d["code"] == code && d["severity"] == "blocking"), "{what}: expected {code}, got {:?}", codes(&out));
    }
}

fn two_span_held() -> Value {
    let docs = documents();
    let mut model = docs["DOC-2S-SPRING"].0.clone();
    model["load_cases"] = json!([model["load_cases"].as_array().unwrap().iter().find(|c| c["id"] == "HT-2S-SPRING-HELD").unwrap().clone()]);
    model
}

/// The three refusal scenarios of the package, each by name with no result,
/// and the remaining named refusals of REQ-011 and REQ-014.
#[test]
fn each_refusal_is_raised_by_name_with_no_result() {
    // REFUSE-TEST-ON-PRESSURE-FREE-ROUTE.
    let mut pressure_free = two_span_held();
    pressure_free.as_object_mut().unwrap().remove("pressure_contract");
    for pipe in pressure_free["pipe_segments"].as_array_mut().unwrap() {
        pipe["section"].as_object_mut().unwrap().remove("corrosion_allowance");
    }
    for case in pressure_free["load_cases"].as_array_mut().unwrap() {
        case.as_object_mut().unwrap().remove("pressure_regions");
        case.as_object_mut().unwrap().remove("condition_use");
    }
    pressure_free["materials"] = json!([{"id": "material:ht", "elastic_modulus": qv(input("E"), "Pa"),
        "shear_modulus": qv(input("E") / (2.0 * (1.0 + input("nu"))), "Pa"), "provenance": PROV}]);
    refused(&pressure_free, "LOAD_CASE_TEST_CONDITION_PRESSURE_FREE", "REFUSE-TEST-ON-PRESSURE-FREE-ROUTE");

    // REFUSE-HELD-DUPLICATE-ON-ONE-DOF.
    let mut duplicate = two_span_held();
    duplicate["supports"].as_array_mut().unwrap().push(json!({"id": "support:b-ce", "node": "node:b", "family": "constant_effort_support", "restraints": ["UZ"],
        "hanger": {"hanger_type": "constant_effort_support", "constant_load": qv(input("Fce_2s"), "N"), "travel_range": qv(0.05, "m"), "source_reference": "invented"},
        "provenance": PROV}));
    refused(&duplicate, "LOAD_CASE_TEST_HELD_SUPPORT_DUPLICATE", "REFUSE-HELD-DUPLICATE-ON-ONE-DOF");

    // REFUSE-HELD-ON-RESTRAINED-DOF.
    let mut restrained = two_span_held();
    restrained["supports"].as_array_mut().unwrap().push(json!({"id": "support:b-rigid", "node": "node:b", "family": "vertical_support", "restraints": ["UZ"], "provenance": PROV}));
    refused(&restrained, "LOAD_CASE_TEST_HELD_SUPPORT_RESTRAINED", "REFUSE-HELD-ON-RESTRAINED-DOF");

    // A constant-effort support whose acted degree of freedom is not entered.
    let mut unformed = documents()["DOC-2S-CE"].0.clone();
    unformed["supports"].as_array_mut().unwrap().iter_mut().find(|s| s["id"] == "support:b").unwrap()["restraints"] = json!(["UZ", "UY"]);
    refused(&unformed, "LOAD_CASE_TEST_HELD_SUPPORT_UNFORMED", "held constant-effort support with two translational restraints");

    // No contents selection.
    let mut unselected = two_span_held();
    unselected["load_cases"][0].as_object_mut().unwrap().remove("condition_use");
    refused(&unselected, "LOAD_CASE_TEST_CONTENTS_UNSELECTED", "a test case with no contents selection");

    // A selection with no generated self-weight to enter.
    let mut weightless = two_span_held();
    weightless["load_cases"][0]["primitive_loads"] = json!([]);
    refused(&weightless, "LOAD_CASE_TEST_CONTENTS_SELF_WEIGHT_INVALID", "a test case with no generated self-weight");

    // A selected key the pipe's set does not have.
    let mut missing = two_span_held();
    missing["load_cases"][0]["condition_use"] = json!({"contents_density": "NOPE"});
    refused(&missing, "OPERATING_CONDITION_KEY_MISSING", "a selected key the set lacks");

    // A stale generated self-weight (the section changed after generation).
    let mut stale = two_span_held();
    stale["pipe_segments"][0]["section"]["contents_density"] = qv(900.0, "kg/m^3");
    refused(&stale, "SELF_WEIGHT_INPUTS_STALE", "a stale generated self-weight in a test case");

    // A combination with a test case among its operands, directly and through another.
    let mut combined = documents()["DOC-2S-SPRING"].0.clone();
    combined["combinations"] = json!([
        {"id": "C-DIRECT", "label": "Direct", "basis": "mechanics", "terms": [{"load_case": "HT-2S-SPRING-HELD", "factor": 1.0}], "provenance": PROV},
    ]);
    refused(&combined, "COMBINATION_HYDROSTATIC_TEST_WITHHELD", "a combination over a test case");
    let mut nested = documents()["DOC-2S-SPRING"].0.clone();
    nested["combinations"] = json!([
        {"id": "C-INNER", "label": "Inner", "basis": "mechanics", "terms": [{"load_case": "HT-2S-SPRING-NONE", "factor": 1.0}], "provenance": PROV},
        {"id": "C-OUTER", "label": "Outer", "basis": "mechanics", "terms": [{"combination": "C-INNER", "factor": 1.0}, {"load_case": "HT-2S-SPRING-ORDINARY", "factor": 1.0}], "provenance": PROV},
    ]);
    for mode in MODES {
        let out = run(&nested, mode);
        assert_eq!(out["status"]["mechanics"], "MODEL_INCOMPLETE");
        let withheld: Vec<&Value> = out["diagnostics"].as_array().unwrap().iter().filter(|d| d["code"] == "COMBINATION_HYDROSTATIC_TEST_WITHHELD").collect();
        assert_eq!(withheld.len(), 2, "both the combination and the one over it: {:?}", codes(&out));
    }
}
