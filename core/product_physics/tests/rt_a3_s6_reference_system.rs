/// EQ-1/EQ-2 against the independent weight record with RS-P150's distributed
/// weight replaced by RS-R1's 300 N at its CoG; `extra` perturbs the expected
/// total (the mutant control). Returns the worst fraction of the allowance used.
fn check_eq(model: &Value, envelope: &Value, label: &str, extra: f64) -> f64 {
    let r = weight_references();
    let key = &r["key_values"];
    let p150 = r["members"].as_array().unwrap().iter().find(|m| m["member"] == BODY).unwrap();
    let cog = {
        let n = position(model, R1_NODE);
        [n[0] + R1_COG[0], n[1] + R1_COG[1], n[2] + R1_COG[2]]
    };
    let weight = key["W_total_N"]["value"].as_f64().unwrap() - p150["weight_N"]["value"].as_f64().unwrap() + R1_WEIGHT_N + extra;
    let first: Vec<f64> = (0..3).map(|k| key["weight_first_moment_N_m"][k]["value"].as_f64().unwrap() - p150["first_moment_N_m"][k]["value"].as_f64().unwrap() + R1_WEIGHT_N * cog[k]).collect();
    let mut worst: f64 = 0.0;
    for case in CASES {
        let (mut force, mut moment, mut fs, mut ms) = ([0.0; 3], [0.0; 3], 0.0f64, 0.0f64);
        for s in model["supports"].as_array().unwrap() {
            let id = s["id"].as_str().unwrap();
            // RS-CE1's action on the pipe is its constant force along +Z (its applied-load row).
            let f = if id == CE1 { [0.0, 0.0, ce_applied(envelope, case)] } else { ["Fx", "Fy", "Fz"].map(|c| reaction(envelope, id, case, c).0) };
            let m = ["Mx", "My", "Mz"].map(|c| reaction(envelope, id, case, c).0);
            let lever = cross(position(model, s["node"].as_str().unwrap()), f);
            for k in 0..3 {
                force[k] += f[k];
                moment[k] += m[k] + lever[k];
                fs = fs.max(f[k].abs());
                ms = ms.max(m[k].abs());
            }
        }
        let mut check = |what: &str, observed: f64, expected: f64, zero_scale: f64| {
            let tol = EQ * if expected != 0.0 { expected.abs() } else { zero_scale };
            assert!((observed - expected).abs() <= tol, "{label} {case} {what}: observed {observed:e}, expected {expected:e}, tolerance {tol:e}");
            worst = worst.max((observed - expected).abs() / tol);
        };
        check("EQ-1 sum Fz", force[2], weight, fs);
        check("EQ-2 sum Fx", force[0], 0.0, fs);
        check("EQ-2 sum Fy", force[1], 0.0, fs);
        for (k, expected) in [first[1], -first[0], 0.0].into_iter().enumerate() {
            check(&format!("EQ-2 M{k}"), moment[k], expected, ms);
        }
    }
    worst
}

