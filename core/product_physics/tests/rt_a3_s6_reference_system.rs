/// `overlay_with`, optionally without RS-G1.
fn overlay_of(intended: bool, nonlinear: bool, gap: bool) -> Value {
    let mut model = fixture();
    let ids = |m: &Value, key: &str| m[key].as_array().unwrap().iter().map(|x| x["id"].as_str().unwrap().to_string()).collect::<BTreeSet<_>>();
    for id in [R1, CE1, LO1, FR1, G1] {
        assert!(!ids(&model, "components").contains(id) && !ids(&model, "supports").contains(id), "the maintained fixture now carries {id}: solve it instead");
    }
    let components = model["components"].as_array_mut().unwrap();
    let at = components.iter().position(|c| c["kind"] == "expansion_joint").unwrap();
    components.insert(at, r1());
    for (after, record) in supports(intended, nonlinear).into_iter().filter(|(_, record)| gap || record["id"] != G1) {
        let list = model["supports"].as_array_mut().unwrap();
        let id = record["id"].as_str().unwrap().to_string();
        if let Some(existing) = list.iter().position(|s| s["id"] == id.as_str()) {
            list[existing] = record;
            continue;
        }
        let at = list.iter().position(|s| s["id"] == after).unwrap() + 1;
        list.insert(at, record);
        for case in model["load_cases"].as_array_mut().unwrap() {
            let states = case["analysis_state"]["support_states"].as_array_mut().unwrap();
            let at = states.iter().position(|s| s["support_ref"] == after).unwrap() + 1;
            states.insert(at, json!({"support_ref": id, "participation": {"kind": "active_model_device"}}));
        }
    }
    let mut base = model.clone();
    base["load_cases"] = json!([]);
    base["combinations"] = json!([]);
    let source_hash = format!("sha256:{:x}", Sha256::digest(canonical_json(&base).as_bytes()));
    let typed: PreviewModel = serde_json::from_value(base).expect("the overlaid model parses");
    let pipes = weighted_pipes(&model);
    for case in model["load_cases"].as_array_mut().unwrap() {
        let request = SelfWeightRequest {
            case_id: case["id"].as_str().unwrap().into(),
            label: case["label"].as_str().unwrap().into(),
            pipe_refs: pipes.clone(),
            gravity: SelfWeightGravity { value: -9.80665, unit: "m/s^2".into(), axis: "global_z".into() },
            provenance: case["provenance"].as_str().unwrap().into(),
            source_model_hash: source_hash.clone(),
        };
        let plan = generate_self_weight_operations(&typed, &request).unwrap_or_else(|d| panic!("self-weight generation refused: {d:?}"));
        assert!(plan.warnings.is_empty(), "{:?}", plan.warnings);
        let loads: Vec<Value> = plan.changes[1..].iter().map(|c| serde_json::from_str(&c.after).unwrap()).collect();
        case["analysis_state"]["load_sources"] = json!(loads.iter().map(|l| json!({"source_ref": l["id"], "factor": 1.0})).collect::<Vec<_>>());
        case["primitive_loads"] = json!(loads);
    }
    model
}

/// The overlay changes only what it names: nodes, members, sections, materials,
/// regions, case identities, states other than the added support states, and
/// combinations are the fixture's.
fn check_overlay_identity(model: &Value) {
    let f = fixture();
    for key in ["nodes", "pipe_segments", "sections", "materials", "combinations", "reference_configurations", "pressure_contract"] {
        assert_eq!(model[key], f[key], "{key}");
    }
    let (cases, original) = (model["load_cases"].as_array().unwrap(), f["load_cases"].as_array().unwrap());
    assert_eq!(cases.len(), original.len());
    let added: BTreeSet<&str> = [CE1, LO1, FR1, G1].into();
    let _ = &added;
    for (c, o) in cases.iter().zip(original) {
        for key in ["id", "label", "kind", "status", "provenance", "pressure_regions"] {
            assert_eq!(c[key], o[key], "{}: {key}", o["id"]);
        }
        for key in ["contract", "element_states", "history", "reference_configuration_ref"] {
            assert_eq!(c["analysis_state"][key], o["analysis_state"][key], "{}: {key}", o["id"]);
        }
        let kept: Vec<&Value> = c["analysis_state"]["support_states"].as_array().unwrap().iter()
            .filter(|s| !added.contains(s["support_ref"].as_str().unwrap())).collect();
        assert_eq!(kept, o["analysis_state"]["support_states"].as_array().unwrap().iter().collect::<Vec<_>>(), "{}", o["id"]);
    }
    let kept: Vec<&Value> = model["supports"].as_array().unwrap().iter().filter(|s| !added.contains(s["id"].as_str().unwrap())).collect();
    assert_eq!(kept, f["supports"].as_array().unwrap().iter().collect::<Vec<_>>());
}

