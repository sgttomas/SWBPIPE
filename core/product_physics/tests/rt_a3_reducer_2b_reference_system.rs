/// Every pipe the fixture's W requests select: every member but the span the
/// expansion joint replaces.
fn weighted_pipes(model: &Value) -> Vec<String> {
    let replaced: Vec<&Value> = model["components"].as_array().unwrap().iter()
        .filter_map(|c| c.get("objective_connector").map(|o| &o["topology"]["span_ref"])).collect();
    assert_eq!(replaced, [&json!("pipe:RS-P180")]);
    model["pipe_segments"].as_array().unwrap().iter().map(|p| p["id"].as_str().unwrap().to_string())
        .filter(|p| p != "pipe:RS-P180").collect()
}

struct Overlay {
    model: Value,
    /// The canonical sha256 of the overlaid model without cases and combinations (the generator's input).
    source_hash: String,
    scope: Vec<String>,
}

/// The fixture with `shear_model` set and, unless `component` is None, that
/// component inserted before the expansion joint and W regenerated on the
/// result; with `refresh` false the fixture's W is kept (the stale control).
fn overlay(shear: &str, component: Option<Value>, refresh: bool) -> Overlay {
    let mut model = fixture();
    // The overlay exists because the fixture and its weight record omit RS-R1
    // (its DEL-09-01 §10 row is pending). Once they adopt it, solve the
    // fixture itself and re-derive the expected weight; do not overlay twice.
    assert!(model["components"].as_array().unwrap().iter().all(|c| c["id"] != R1), "the maintained fixture now carries RS-R1");
    assert!(weight_references()["components"].as_array().unwrap().iter().all(|c| c["component"] != R1), "the weight record now carries RS-R1");
    model["pressure_contract"]["shear_model"] = json!(shear);
    if let Some(component) = component {
        let components = model["components"].as_array_mut().unwrap();
        let at = components.iter().position(|c| c["kind"] == "expansion_joint").unwrap();
        components.insert(at, component);
    }
    let mut base = model.clone();
    base["load_cases"] = json!([]);
    base["combinations"] = json!([]);
    let source_hash = format!("sha256:{:x}", Sha256::digest(canonical_json(&base).as_bytes()));
    let mut scope = Vec::new();
    if refresh {
        let typed: PreviewModel = serde_json::from_value(base).expect("the overlaid model parses");
        let pipes = weighted_pipes(&model);
        for case in model["load_cases"].as_array_mut().unwrap() {
            // The fixture's rule: one source per primitive, factor 1.
            let sources: Vec<Value> = case["primitive_loads"].as_array().unwrap().iter().map(|l| json!({"source_ref": l["id"], "factor": 1.0})).collect();
            assert_eq!(case["analysis_state"]["load_sources"], json!(sources), "the fixture's load_sources rule");
            let request = SelfWeightRequest {
                case_id: case["id"].as_str().unwrap().into(),
                label: case["label"].as_str().unwrap().into(),
                pipe_refs: pipes.clone(),
                gravity: SelfWeightGravity { value: -9.80665, unit: "m/s^2".into(), axis: "global_z".into() },
                provenance: case["provenance"].as_str().unwrap().into(),
                source_model_hash: source_hash.clone(),
            };
            let plan = generate_self_weight_operations(&typed, &request).unwrap_or_else(|d| panic!("self-weight generation refused: {d:?}"));
            assert!(plan.warnings.is_empty(), "{:?}", plan.warnings);
            assert_eq!(plan.changes[0].change_kind, "create_load_case");
            assert!(plan.changes[1..].iter().all(|c| c.change_kind == "create_primitive_load"));
            let drafted: Value = serde_json::from_str(&plan.changes[0].after).unwrap();
            for key in ["id", "label", "kind", "status", "provenance"] {
                assert_eq!(drafted[key], case[key], "{key}: the drafted case record is the fixture's");
            }
            scope.push(plan.scope_label.clone());
            let loads: Vec<Value> = plan.changes[1..].iter().map(|c| serde_json::from_str(&c.after).unwrap()).collect();
            case["analysis_state"]["load_sources"] = json!(loads.iter().map(|l| json!({"source_ref": l["id"], "factor": 1.0})).collect::<Vec<_>>());
            case["primitive_loads"] = json!(loads);
        }
    }
    Overlay { model, source_hash, scope }
}

