//! RT-A3 reducer increment 2b on the full reference system (DEL-09-01
//! design §5 RS-R1; DEL-04-07, the eccentric reducer pressure step;
//! DEL-03-05, the eccentric reducer offset and rigid component
//! stiffness scaling): the RS-R1
//! connecting path through PP's public entry, with weight, pressure, the
//! temperature modulus state, thermal eigenstrain and boundary motion together.
//!
//! **Input.** The maintained fixture `fixtures/reference_system/reference_system.json`
//! (read only), with the specified RS-R1 overlaid in this test only: a
//! `reducer` at RS-160 mapping RS-P150 as `mechanics_geometry_only`, the
//! declared offset (0, 0, +25) mm, end sizes 270/220 mm, weight 300 N with its
//! centre of gravity at the body midpoint (global, from the component's node)
//! and the DEC-045 scale 2. No node moves and no region, support, material,
//! other component, case state or combination changes; the test checks that.
//! Inserting the component changes the consumed self-weight basis, so W is
//! regenerated by the product's own generator
//! (`self_weight::generate_self_weight_operations`, the producer behind
//! `self_weight_wasm`) on the overlaid model with its own source hash, the
//! fixture's requests, and the fixture's rule for `load_sources`. The
//! fixture's captured W is never replayed; doing so is the stale-weight
//! negative control. The fixture's contract is Euler-Bernoulli; the test also
//! switches `shear_model` to `timoshenko_annulus_energy_v1`. Nothing here
//! adopts RS-R1 into the maintained fixture or its pending ledger.
//!
//! **What is independent and what is not.** The closed numerical basis for the
//! eccentric step remains the 27 exact 3-D reference cases bound by
//! `rt_a3_reducer_2b_references.rs`. No independent global solution of the
//! 27-node system exists, and none is claimed. On the full model this file
//! checks the following relations. Loads, geometry and constitutive parameters
//! are computed here from the inputs. Local recovery uses the product's
//! published motions, and section checks use its actions; these consistency
//! relations do not supply independent global displacements or reactions:
//! - total weight and its first moment (EQ-1, EQ-2): the frozen independent
//!   `validation/references/reference_system/` totals, less RS-P150's
//!   distributed weight from the same record, plus 300 N at the body midpoint;
//!   EQ-5 on RS-dSAM;
//! - the generated W: every member intensity equals the record's section
//!   weight per length, RS-P150 has none, and RS-R1's wrench is F = (0, 0, -300) N
//!   with M = r x F;
//! - local formation and recovery on the body and both neighbours. The product's
//!   published end wrenches equal an independently assembled member stiffness
//!   (s*E, s*G on the nominal annulus, kappa_E, frame from the chord and
//!   y_reference) times the product's displacements, less the independently
//!   formed eigen actions: thermal s*E*A_n*alpha*dT at the case's modulus
//!   state, the unscaled Poisson pair 2*nu*p*A_i, and the uniform weight from
//!   the reference record on the neighbours only. The tolerance is an a priori
//!   rounding bound, 1e-12 of the sum of the absolute terms. This checks the
//!   relation, not the displacements;
//! - nodal equilibrium at RS-150 and RS-160 against independently formed caps
//!   -p*A_i*s at the actual nodes along each member's own axis, plus the
//!   RS-R1 weight wrench. No other force or moment acts, so no p*A*e term
//!   exists;
//! - body station statics, wall/effective force, stress, extreme and Lamé
//!   relations on both section bases, and the reference-section record;
//! - mutants of the recovery and equilibrium checks that miss by orders of
//!   magnitude. These show that the checks discriminate. They are not
//!   references.
//!
//! Product consistency controls, which are not mathematical references, are
//! the diagnostics against the unmodified fixture solved alike and a
//! rigid-family surrogate with the same body, scale and weight but no
//! reducer branch, which gives bit-identical rows.
