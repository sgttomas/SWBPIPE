/// The published formation evidence: the body takes the contract's beam
/// theory (with kappa_E under Timoshenko), realized bends stay Euler-Bernoulli,
/// and RG-R's caps and Poisson pair are formed on the actual chord, unscaled.
fn check_evidence(model: &Value, envelope: &Value, shear: &str, label: &str) {
    let [p140, body, p160] = neighbourhood();
    let evidence = &envelope["contract_evidence"];
    for case in CASES {
        let exact = evidence["exact_cases"].as_array().unwrap().iter().find(|c| c["load_case_id"] == case).unwrap();
        let mut arcs = 0;
        for s in exact["pipe_sections"].as_array().unwrap() {
            let theory = &s["beam_theory"];
            if s["member_kind"] == "realized_arc" {
                arcs += 1;
                assert_eq!(theory, &json!({"model": EB}), "{label} {case} {}: realized bends are Euler-Bernoulli under either model", s["pipe_id"]);
            } else {
                assert_eq!(theory["model"], shear, "{label} {case} {}", s["pipe_id"]);
            }
            if s["pipe_id"] == BODY && shear == TIMO {
                let (_, nu, _) = member_state(model, case, BODY);
                let kappa = section(model, BODY, nu).kappa;
                assert!((theory["shear_factor"].as_f64().unwrap() - kappa).abs() <= 1e-12 * kappa, "{label} {case}: kappa_E {theory} vs {kappa}");
            }
        }
        assert_eq!(arcs, 3, "{label} {case}");
        let p = case_pressure(model, case);
        let (_, nu, _) = member_state(model, case, BODY);
        let ai = section(model, BODY, nu).ai;
        let region = |name: &str| {
            let short = case.trim_start_matches("load:");
            evidence["pressure"].as_array().unwrap().iter().find(|r| r["load_case_id"] == case && r["region_id"] == format!("region:{short}-{name}").as_str()).unwrap()
        };
        let rgr = region("RG-R");
        assert_eq!(rgr["member_pipe_ids"], json!([BODY]));
        let applied = &rgr["applied_loads"].as_array().unwrap()[0];
        let (_, r) = frame(model, &body);
        let close3 = |what: &str, observed: &Value, expected: [f64; 3], size: f64| {
            for k in 0..3 {
                let o = observed[k].as_f64().unwrap();
                assert!((o - expected[k]).abs() <= LOCAL * size, "{label} {case} {what}: {observed} vs {expected:?}");
            }
        };
        close3("RG-R local x (the chord, not the run axis)", &applied["local_x_global"], r[0], 1.0);
        let pair = [applied["eigenload_pair_local_n"][0].as_f64().unwrap(), applied["eigenload_pair_local_n"][1].as_f64().unwrap()];
        assert!((pair[0] - 2.0 * nu * p * ai).abs() <= LOCAL * p * ai && pair[1] == -pair[0], "{label} {case}: the Poisson pair is unscaled, {pair:?}");
        for (name, m, node) in [("RG-R", &body, F), ("RG-R", &body, N), ("RG-3", &p140, F), ("RG-4", &p160, N)] {
            let terminal = region(name)["terminals"].as_array().unwrap().iter().find(|t| t["node_ref"] == node).unwrap();
            assert_eq!(terminal["closure_transfer"], "transfers_to_wall");
            close3(&format!("{name} cap at {node}"), &terminal["closure_pressure_load_global_n"], cap(model, case, m, node), p * ai);
        }
    }
}

const MUTANTS: [Mutant; 5] = [Mutant::BodyUnscaled, Mutant::PoissonScaled, Mutant::ReferenceModulus, Mutant::NoThermalStrain, Mutant::BodyKeepsPipeWeight];

/// One overlaid, solved configuration: every local and global check; returns
/// the worst fraction of an allowance used per family, and the smallest miss
/// (in allowances) of any mutant.
fn check_configuration(o: &Overlay, envelope: &Value, shear: &str, label: &str) -> (BTreeMap<&'static str, f64>, f64) {
    let model = &o.model;
    let rows = Rows::new(envelope);
    let mut worst: BTreeMap<&'static str, f64> = BTreeMap::new();
    let mut weakest = f64::INFINITY;
    let mut note = |family: &'static str, used: f64| {
        let w = worst.entry(family).or_insert(0.0);
        *w = w.max(used);
    };
    note("EQ-1/EQ-2/EQ-5 (1e-9)", check_eq(model, &rows, label));
    for case in CASES {
        let members = neighbourhood();
        let recs = members.map(|m| recover(model, &rows, case, shear, &m, Mutant::None));
        for (m, rec) in members.iter().zip(&recs) {
            let miss = recovery_miss(&rows, case, m, rec);
            assert!(miss <= 1.0, "{label} {case} {}: recovery misses its allowance by {miss:e}", m.pipe);
            note(if m.pipe == BODY { "body recovery" } else { "neighbour recovery" }, miss);
        }
        for node in [F, N] {
            let miss = equilibrium_miss(&rows, case, node, &recs, external(model, case, node));
            assert!(miss <= 1.0, "{label} {case} {node}: equilibrium misses its allowance by {miss:e}");
            note("nodal equilibrium", miss);
        }
        // The j-end block bounds of the body's recovery bound its station actions.
        let end_j = rows.local_end(BODY, case, "end_j");
        note("body sections", check_body_sections(model, &rows, case, end_j, (recs[1].bound[2], recs[1].bound[3]), label));
        // The checks discriminate: each mutant misses by orders of magnitude.
        for mutant in MUTANTS {
            if matches!(mutant, Mutant::ReferenceModulus | Mutant::NoThermalStrain) && case != "load:RS-OPE" {
                continue;
            }
            let rec = recover(model, &rows, case, shear, &members[1], mutant);
            let miss = recovery_miss(&rows, case, &members[1], &rec);
            assert!(miss > 1e3, "{label} {case} {mutant:?}: the body recovery check does not discriminate ({miss:e})");
            weakest = weakest.min(miss);
        }
        // A p·A·e moment at N, or N's body cap turned to the run axis, breaks equilibrium.
        let p = case_pressure(model, case);
        let ai = section(model, BODY, member_state(model, case, BODY).1).ai;
        let mut extra = external(model, case, N);
        extra[3] += p * ai * 0.025;
        let pae = equilibrium_miss(&rows, case, N, &recs, extra);
        let mut averaged = external(model, case, N);
        let body_cap = cap(model, case, &members[1], N);
        let run_cap = scale([0.0, 1.0, 0.0], p * ai);
        for k in 0..3 {
            averaged[k] += run_cap[k] - body_cap[k];
        }
        let axis = equilibrium_miss(&rows, case, N, &recs, averaged);
        assert!(pae > 1e3 && axis > 1e3, "{label} {case}: equilibrium does not discriminate (pAe {pae:e}, run-axis cap {axis:e})");
        weakest = weakest.min(pae.min(axis));
    }
    // Combinations: RS-EXP = RS-OPE - RS-SUS and RS-dSAM = RS-SAM - RS-SUS on
    // the neighbourhood's motions and end wrenches.
    for (combination, minuend) in [("combination:RS-EXP", "load:RS-OPE"), ("combination:RS-dSAM", "load:RS-SAM")] {
        let mut pairs = Vec::new();
        for node in ["node:RS-140", F, N, "node:RS-170"] {
            let (c, a, b) = (rows.motion(node, combination), rows.motion(node, minuend), rows.motion(node, "load:RS-SUS"));
            pairs.extend((0..6).map(|k| (c[k], a[k], b[k])));
        }
        for m in neighbourhood() {
            for location in ["end_i", "end_j"] {
                let (c, a, b) = (rows.global_end(m.pipe, combination, location), rows.global_end(m.pipe, minuend, location), rows.global_end(m.pipe, "load:RS-SUS", location));
                pairs.extend((0..6).map(|k| (c[k], a[k], b[k])));
            }
        }
        for (c, a, b) in pairs {
            assert!((c - (a - b)).abs() <= LOCAL * (a.abs() + b.abs()), "{label} {combination}: {c:e} vs {a:e} - {b:e}");
        }
    }
    (worst, weakest)
}

