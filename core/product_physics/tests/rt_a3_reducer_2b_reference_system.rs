struct Section {
    ro: f64,
    ri_nominal: f64,
    ri_reduced: f64,
    an: f64,
    i: f64,
    ai: f64,
    kappa: f64,
}

fn mm(v: &Value) -> f64 {
    assert_eq!(v["unit"], "mm");
    v["value"].as_f64().unwrap() / 1000.0
}

/// The annulus from the authored section (D-5: stiffness on the nominal wall,
/// the pressure bore on the wall less mill tolerance and corrosion allowance),
/// with the energy-matched annular shear factor kappa_E.
fn section(model: &Value, pipe: &str, nu: f64) -> Section {
    let s = &model["pipe_segments"].as_array().unwrap().iter().find(|p| p["id"] == pipe).unwrap()["section"];
    let (d, t, cm, ca) = (mm(&s["outside_diameter"]), mm(&s["wall_thickness"]), mm(&s["mill_tolerance"]), mm(&s["corrosion_allowance"]));
    let ro = d / 2.0;
    let ri_nominal = ro - t;
    let ri_reduced = ro - ((t - cm) - ca);
    let m2 = (ri_nominal / ro).powi(2);
    let (a, b, n1) = (1.0 + m2, 1.0 - m2, 1.0 + nu);
    let c = (8.0 * nu + 14.0) * nu + 7.0;
    let kappa = 6.0 * n1 * n1 * a * a / (c * b * b + 48.0 * m2 * n1 * n1);
    let pi = std::f64::consts::PI;
    Section { ro, ri_nominal, ri_reduced, an: pi * (ro * ro - ri_nominal * ri_nominal), i: pi / 4.0 * (ro.powi(4) - ri_nominal.powi(4)),
        ai: pi * ri_reduced * ri_reduced, kappa }
}

/// The case's material state for one member, read from its element state:
/// (E, nu, free thermal strain).
fn member_state(model: &Value, case: &str, pipe: &str) -> (f64, f64, f64) {
    let material = &model["materials"][0];
    let gpa = |v: &Value| {
        assert_eq!(v["unit"], "GPa");
        v["value"].as_f64().unwrap() * 1e9
    };
    let points: Vec<(f64, f64, f64, String)> = material["temperature_points"].as_array().unwrap().iter()
        .map(|p| (p["temperature"]["value"].as_f64().unwrap(), gpa(&p["elastic_modulus"]), p["poisson_ratio"]["value"].as_f64().unwrap(), p["id"].as_str().unwrap().to_string()))
        .collect();
    let case = model["load_cases"].as_array().unwrap().iter().find(|c| c["id"] == case).unwrap();
    let state = case["analysis_state"]["element_states"].as_array().unwrap().iter().find(|s| s["pipe_ref"] == pipe).unwrap();
    let selection = &state["material_selection"];
    let (e, nu) = match selection["kind"].as_str().unwrap() {
        "exact_point" => {
            let p = points.iter().find(|p| selection["point_ref"] == p.3.as_str()).unwrap();
            (p.1, p.2)
        }
        "temperature_interpolation" => {
            assert_eq!(selection["interpolation"], "piecewise_linear");
            let t = selection["temperature"]["value"].as_f64().unwrap();
            let k = points.windows(2).position(|w| w[0].0 <= t && t <= w[1].0).unwrap();
            let (a, b) = (&points[k], &points[k + 1]);
            assert_eq!(a.2, b.2);
            (a.1 + (t - a.0) / (b.0 - a.0) * (b.1 - a.1), a.2)
        }
        other => panic!("unexpected selection {other}"),
    };
    let strain = match state["thermal_state"]["kind"].as_str().unwrap() {
        "unchanged_reference" => 0.0,
        "free_length_state" => {
            let law = material["expansion_laws"].as_array().unwrap().iter().find(|l| l["id"] == state["thermal_state"]["expansion_law_ref"]).unwrap();
            assert_eq!(law["definition"], "engineering_secant");
            assert_eq!(law["data"]["kind"], "constant");
            let alpha = law["data"]["coefficient"]["value"].as_f64().unwrap();
            alpha * (state["operating_temperature"]["value"].as_f64().unwrap() - law["datum_temperature"]["value"].as_f64().unwrap())
        }
        other => panic!("unexpected thermal state {other}"),
    };
    (e, nu, strain)
}

fn case_pressure(model: &Value, case: &str) -> f64 {
    let case = model["load_cases"].as_array().unwrap().iter().find(|c| c["id"] == case).unwrap();
    let p: Vec<f64> = case["pressure_regions"].as_array().unwrap().iter().map(|r| {
        assert_eq!(r["pressure"]["unit"], "kPa");
        r["pressure"]["value"].as_f64().unwrap() * 1000.0
    }).collect();
    assert!(p.windows(2).all(|w| w[0] == w[1]), "one pressure (D-1 unequal closures not exercised here)");
    p[0]
}

/// A member of the RS-R1 neighbourhood: its pipe, ends, scale and the uniform
/// weight it carries (N/m along global -Z; zero on the replaced body).
#[derive(Clone, Copy)]
struct Member {
    pipe: &'static str,
    from: &'static str,
    to: &'static str,
    scale: f64,
    weight_per_length: f64,
}

/// The local frame: x along the chord, y from y_reference made orthogonal to
/// x, z = x × y (the frame the 2b packet's generator uses).
fn frame(model: &Value, m: &Member) -> (f64, [[f64; 3]; 3]) {
    let d = sub(position(model, m.to), position(model, m.from));
    let length = norm(d);
    let x = scale(d, 1.0 / length);
    let y_ref = &model["pipe_segments"].as_array().unwrap().iter().find(|p| p["id"] == m.pipe).unwrap()["y_reference"];
    let y_ref = [y_ref["x"].as_f64().unwrap(), y_ref["y"].as_f64().unwrap(), y_ref["z"].as_f64().unwrap()];
    let y = sub(y_ref, scale(x, dot(y_ref, x)));
    let y = scale(y, 1.0 / norm(y));
    (length, [x, y, cross(x, y)])
}

/// The 12x12 local frame stiffness, Euler-Bernoulli (gas None) or Timoshenko.
fn local_k(length: f64, ea: f64, ei: f64, gj: f64, gas: Option<f64>) -> [[f64; 12]; 12] {
    let mut k = [[0.0; 12]; 12];
    let mut put = |i: usize, j: usize, v: f64| {
        k[i][j] += v;
        if i != j {
            k[j][i] += v;
        }
    };
    put(0, 0, ea / length);
    put(6, 6, ea / length);
    put(0, 6, -ea / length);
    put(3, 3, gj / length);
    put(9, 9, gj / length);
    put(3, 9, -gj / length);
    let phi = gas.map_or(0.0, |gas| 12.0 * ei / (gas * length * length));
    let a = 12.0 * ei / (1.0 + phi) / length.powi(3);
    let b = 6.0 * ei / (1.0 + phi) / length.powi(2);
    let c = (4.0 + phi) * ei / (1.0 + phi) / length;
    let d = (2.0 - phi) * ei / (1.0 + phi) / length;
    // x-y plane (v = u_y, theta = r_z)
    for (i, j, v) in [(1, 1, a), (1, 5, b), (1, 7, -a), (1, 11, b), (5, 5, c), (5, 7, -b), (5, 11, d), (7, 7, a), (7, 11, -b), (11, 11, c)] {
        put(i, j, v);
    }
    // x-z plane (w = u_z, theta = -w')
    for (i, j, v) in [(2, 2, a), (2, 4, -b), (2, 8, -a), (2, 10, -b), (4, 4, c), (4, 8, b), (4, 10, d), (8, 8, a), (8, 10, b), (10, 10, c)] {
        put(i, j, v);
    }
    k
}

/// A deliberate departure of the independent model (a mutant of the check).
#[derive(Clone, Copy, PartialEq, Debug)]
enum Mutant {
    None,
    BodyUnscaled,
    PoissonScaled,
    ReferenceModulus,
    NoThermalStrain,
    BodyKeepsPipeWeight,
}

/// The independent end actions of one member from the product's
/// displacements: f = k·T·u - f_eq, local and global, with each end-block's
/// rounding bound (the sum of the absolute terms of its three rows).
struct Recovered {
    local: [f64; 12],
    global: [f64; 12],
    bound: [f64; 4],
}

fn recover(model: &Value, rows: &Rows, case: &str, shear: &str, m: &Member, mutant: Mutant) -> Recovered {
    let (length, r) = frame(model, m);
    let (mut e, nu, mut strain) = member_state(model, case, m.pipe);
    let body = m.pipe == BODY;
    if mutant == Mutant::ReferenceModulus {
        e = member_state(model, "load:RS-SUS", m.pipe).0;
    }
    if mutant == Mutant::NoThermalStrain {
        strain = 0.0;
    }
    let s = if body && mutant == Mutant::BodyUnscaled { 1.0 } else { m.scale };
    let sec = section(model, m.pipe, nu);
    let (se, sg) = (s * e, s * e / (2.0 * (1.0 + nu)));
    let k = local_k(length, se * sec.an, se * sec.i, sg * 2.0 * sec.i, (shear == TIMO).then_some(sg * sec.kappa * sec.an));
    let mut u = [0.0; 12];
    u[..6].copy_from_slice(&rows.motion(m.from, case));
    u[6..].copy_from_slice(&rows.motion(m.to, case));
    let mut ul = [0.0; 12];
    for block in 0..4 {
        for i in 0..3 {
            ul[3 * block + i] = (0..3).map(|j| r[i][j] * u[3 * block + j]).sum();
        }
    }
    // Equivalent nodal actions: thermal (ends pushed apart), the Poisson pair
    // (ends pulled together, no E), and a uniform global -Z load.
    let p = case_pressure(model, case);
    let mut poisson = 2.0 * nu * p * sec.ai;
    if body && mutant == Mutant::PoissonScaled {
        poisson *= s;
    }
    let thermal = se * sec.an * strain;
    let mut fe = [0.0; 12];
    fe[0] = poisson - thermal;
    fe[6] = -poisson + thermal;
    let w = if body && mutant == Mutant::BodyKeepsPipeWeight { body_pipe_weight_per_length() } else { m.weight_per_length };
    let ql = [-w * r[0][2], -w * r[1][2], -w * r[2][2]];
    fe[0] += ql[0] * length / 2.0;
    fe[6] += ql[0] * length / 2.0;
    fe[1] += ql[1] * length / 2.0;
    fe[7] += ql[1] * length / 2.0;
    fe[5] += ql[1] * length * length / 12.0;
    fe[11] -= ql[1] * length * length / 12.0;
    fe[2] += ql[2] * length / 2.0;
    fe[8] += ql[2] * length / 2.0;
    fe[4] -= ql[2] * length * length / 12.0;
    fe[10] += ql[2] * length * length / 12.0;
    let mut local = [0.0; 12];
    let mut bound = [0.0; 4];
    for i in 0..12 {
        local[i] = (0..12).map(|j| k[i][j] * ul[j]).sum::<f64>() - fe[i];
        bound[i / 3] += (0..12).map(|j| (k[i][j] * ul[j]).abs()).sum::<f64>() + fe[i].abs();
    }
    let mut global = [0.0; 12];
    for block in 0..4 {
        for j in 0..3 {
            global[3 * block + j] = (0..3).map(|i| r[i][j] * local[3 * block + i]).sum();
        }
    }
    Recovered { local, global, bound }
}

fn weight_references() -> &'static Value {
    static PARSED: std::sync::OnceLock<Value> = std::sync::OnceLock::new();
    PARSED.get_or_init(|| serde_json::from_str(WEIGHT_REFERENCES).unwrap())
}

/// The independent record's weight per length of a section (N/m).
fn weight_per_length(section: &str) -> f64 {
    let r = weight_references();
    r["sections"].as_array().unwrap().iter().find(|s| s["section"] == section).unwrap()["weight_per_length_N_m"]["value"].as_f64().unwrap()
}

fn body_pipe_weight_per_length() -> f64 {
    weight_per_length("section:RS-S270")
}

fn neighbourhood() -> [Member; 3] {
    [
        Member { pipe: "pipe:RS-P140", from: "node:RS-140", to: F, scale: 1.0, weight_per_length: weight_per_length("section:RS-S270") },
        Member { pipe: BODY, from: F, to: N, scale: R1_SCALE, weight_per_length: 0.0 },
        Member { pipe: "pipe:RS-P160", from: N, to: "node:RS-170", scale: 1.0, weight_per_length: weight_per_length("section:RS-S220") },
    ]
}

/// The largest |observed - recovered| / (LOCAL · bound) over a member's end
/// rows (global wrench, local end-DOF actions).
fn recovery_miss(rows: &Rows, case: &str, m: &Member, rec: &Recovered) -> f64 {
    let mut worst: f64 = 0.0;
    for (end, location) in [(0, "end_i"), (1, "end_j")] {
        let global = rows.global_end(m.pipe, case, location);
        let local = rows.local_end(m.pipe, case, location);
        for k in 0..6 {
            let tol = LOCAL * rec.bound[2 * end + k / 3];
            worst = worst.max((global[k] - rec.global[6 * end + k]).abs() / tol);
            worst = worst.max((local[k] - rec.local[6 * end + k]).abs() / tol);
        }
    }
    worst
}

/// A terminal cap -p·A_i·s_into at `node` of member `m` (s_into: the member's
/// direction into the member from that node).
fn cap(model: &Value, case: &str, m: &Member, node: &str) -> [f64; 3] {
    let (_, r) = frame(model, m);
    let (_, nu, _) = member_state(model, case, m.pipe);
    let into = if node == m.from { r[0] } else { scale(r[0], -1.0) };
    scale(into, -case_pressure(model, case) * section(model, m.pipe, nu).ai)
}

/// The independently formed external wrench at RS-150 and RS-160: the caps at
/// the actual nodes along each member's own axis, plus RS-R1's weight.
fn external(model: &Value, case: &str, node: &str) -> [f64; 6] {
    let [p140, body, p160] = neighbourhood();
    let mut w = [0.0; 6];
    let caps = if node == F { add(cap(model, case, &p140, F), cap(model, case, &body, F)) } else { add(cap(model, case, &body, N), cap(model, case, &p160, N)) };
    w[..3].copy_from_slice(&caps);
    if node == N {
        let force = [0.0, 0.0, -R1_WEIGHT_N];
        let moment = cross(R1_COG, force);
        for k in 0..3 {
            w[k] += force[k];
            w[3 + k] += moment[k];
        }
    }
    w
}

/// Nodal equilibrium: the members' published node-on-member wrenches at the
/// node sum to the external wrench. Returns the largest residual over its
/// allowance (LOCAL times the absolute terms plus the members' recovery bounds).
fn equilibrium_miss(rows: &Rows, case: &str, node: &str, recs: &[Recovered; 3], ext: [f64; 6]) -> f64 {
    let [p140, body, p160] = neighbourhood();
    let ends: [(&Member, &str, usize); 2] = if node == F { [(&p140, "end_j", 1), (&body, "end_i", 0)] } else { [(&body, "end_j", 1), (&p160, "end_i", 0)] };
    let recs: [&Recovered; 2] = if node == F { [&recs[0], &recs[1]] } else { [&recs[1], &recs[2]] };
    let mut worst: f64 = 0.0;
    for part in 0..2 {
        let mut sum = [0.0; 3];
        let mut size = abs3([ext[3 * part], ext[3 * part + 1], ext[3 * part + 2]]);
        for ((m, location, end), rec) in ends.iter().zip(recs) {
            let w = rows.global_end(m.pipe, case, location);
            for k in 0..3 {
                sum[k] += w[3 * part + k];
                size += w[3 * part + k].abs();
            }
            size += rec.bound[2 * end + part];
        }
        for k in 0..3 {
            worst = worst.max((sum[k] - ext[3 * part + k]).abs() / (LOCAL * size));
        }
    }
    worst
}

