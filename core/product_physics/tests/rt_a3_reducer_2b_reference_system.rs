/// Published rows by (kind, entity, basis ref).
struct Rows<'a> {
    by: HashMap<(&'a str, &'a str, &'a str), Vec<&'a Value>>,
}

fn section_basis(row: &Value) -> &str {
    row["metadata"]["basis"].as_str().unwrap_or("").split("; section_basis=").nth(1).unwrap_or("")
}

impl<'a> Rows<'a> {
    fn new(envelope: &'a Value) -> Self {
        let mut by: HashMap<_, Vec<&Value>> = HashMap::new();
        for r in envelope["results"].as_array().unwrap() {
            let basis = r["basis_ref"]["ref_id"].as_str().unwrap_or("");
            by.entry((r["kind"].as_str().unwrap(), r["entity_ref"].as_str().unwrap(), basis)).or_default().push(r);
        }
        Rows { by }
    }

    fn get(&self, kind: &str, entity: &str, basis: &str, location: Option<&str>, component: Option<&str>, section: &str) -> f64 {
        let found: Vec<_> = self.by.get(&(kind, entity, basis)).map(|v| v.as_slice()).unwrap_or(&[]).iter()
            .filter(|r| location.is_none_or(|l| r["metadata"]["location"] == l) && component.is_none_or(|c| r["metadata"]["component"] == c) && section_basis(r) == section)
            .collect();
        assert_eq!(found.len(), 1, "{kind} {entity} {basis} {location:?} {component:?} [{section}]: {} rows", found.len());
        found[0]["value"].as_f64().unwrap()
    }

    /// The node's six global motions, SI (translation rows are mm).
    fn motion(&self, node: &str, basis: &str) -> [f64; 6] {
        let mut u = [0.0; 6];
        for (k, axis) in ["x", "y", "z"].iter().enumerate() {
            let (kt, kr) = (format!("global_nodal_displacement_{axis}"), format!("global_nodal_rotation_{axis}"));
            let t = &self.by[&(kt.as_str(), node, basis)];
            assert_eq!(t.len(), 1);
            assert_eq!(t[0]["unit"], "mm");
            u[k] = t[0]["value"].as_f64().unwrap() / 1000.0;
            let r = &self.by[&(kr.as_str(), node, basis)];
            assert_eq!(r.len(), 1);
            assert_eq!(r[0]["unit"], "rad");
            u[3 + k] = r[0]["value"].as_f64().unwrap();
        }
        u
    }

    /// The published global end wrench of a member at one end (node on member).
    fn global_end(&self, pipe: &str, basis: &str, location: &str) -> [f64; 6] {
        let mut w = [0.0; 6];
        for (k, c) in ["Fx", "Fy", "Fz"].iter().enumerate() {
            w[k] = self.get("element_global_end_force_v1", pipe, basis, Some(location), Some(c), "");
        }
        for (k, c) in ["Mx", "My", "Mz"].iter().enumerate() {
            w[3 + k] = self.get("element_global_end_moment_v1", pipe, basis, Some(location), Some(c), "");
        }
        w
    }

    /// The published element-local end-DOF actions (axial: the wall endpoint action).
    fn local_end(&self, pipe: &str, basis: &str, location: &str) -> [f64; 6] {
        [
            self.get("pipe_wall_endpoint_action_v2", pipe, basis, Some(location), Some("wall_axial_end_action"), ""),
            self.get("element_local_shear_force_y", pipe, basis, Some(location), None, ""),
            self.get("element_local_shear_force_z", pipe, basis, Some(location), None, ""),
            self.get("element_local_torsional_moment", pipe, basis, Some(location), None, ""),
            self.get("element_local_bending_moment_y", pipe, basis, Some(location), None, ""),
            self.get("element_local_bending_moment_z", pipe, basis, Some(location), None, ""),
        ]
    }
}

