//! T4-U1 phase B (T4-I15): short arcs at R = 0.3 m against the intended
//! element. The references are T4-I6's frozen generator `curved_ref.py` at
//! 110 digits, each entry rounded once (`validation/references/t4_i6/
//! t4_i15_short_arc_matrices.py` and its `.stdout.txt`).
use super::*;
use open_pipe_stress_frame_kernel::FrameNode;

struct ShortArc {
    label: &'static str,
    d: [f64; 3],
    y: [f64; 3],
    k: [[f64; 12]; 12],
}

const SECTION: (f64, f64, f64, f64, f64) = (
    200e9,
    80e9,
    0.005969026041820614,
    2.700984283923829e-05,
    5.401968567847658e-05,
);

fn element(xi: [f64; 3], arc: &ShortArc) -> Result<CurvedBendMacroElement, CurvedBendError> {
    let xj = [xi[0] + arc.d[0], xi[1] + arc.d[1], xi[2] + arc.d[2]];
    let (e, g, a, i, j) = SECTION;
    CurvedBendMacroElement::new(
        FrameNode::new(0, xi).unwrap(),
        FrameNode::new(1, xj).unwrap(),
        0.3,
        arc.y,
        e,
        g,
        a,
        i,
        j,
        1.0,
        1.0,
    )
}

/// The unscaled inversion (the solve before T4-U1 phase B).
fn invert_unscaled(matrix: &Matrix6) -> Result<Matrix6, CurvedBendError> {
    let dense: Vec<Vec<f64>> = matrix.iter().map(|row| row.to_vec()).collect();
    let mut inverse = [[0.0; DOF_PER_NODE]; DOF_PER_NODE];
    for col in 0..DOF_PER_NODE {
        let mut rhs = vec![0.0; DOF_PER_NODE];
        rhs[col] = 1.0;
        let solution = solve_dense(&dense, &rhs)?;
        for (row, value) in solution.iter().enumerate() {
            inverse[row][col] = *value;
        }
    }
    for row in 0..DOF_PER_NODE {
        for col in (row + 1)..DOF_PER_NODE {
            let average = 0.5 * (inverse[row][col] + inverse[col][row]);
            inverse[row][col] = average;
            inverse[col][row] = average;
        }
    }
    Ok(inverse)
}

/// Worst row-relative rigid-null residual of K over the six rigid motions of
/// the actual nodes, both sides summed exactly.
fn null_residual(k: &Matrix12, d: [f64; 3]) -> f64 {
    let mut worst = 0.0_f64;
    for mode in 0..6 {
        let mut u = [0.0; 12];
        if mode < 3 {
            u[mode] = 1.0;
            u[6 + mode] = 1.0;
        } else {
            let mut w = [0.0; 3];
            w[mode - 3] = 1.0;
            u[mode] = 1.0;
            u[6 + mode] = 1.0;
            u[6] = w[1] * d[2] - w[2] * d[1];
            u[7] = w[2] * d[0] - w[0] * d[2];
            u[8] = w[0] * d[1] - w[1] * d[0];
        }
        for row in k {
            let mut residual = ExactAccumulator::new();
            let mut magnitude = ExactAccumulator::new();
            for (kv, &uv) in row.iter().zip(&u) {
                residual.add_product(*kv, uv).unwrap();
                magnitude.add_product(kv.abs(), uv.abs()).unwrap();
            }
            let (r, m) = (residual.round().unwrap().abs(), magnitude.round().unwrap());
            assert!(m > 0.0 || r == 0.0);
            if m > 0.0 {
                worst = worst.max(r / m);
            }
        }
    }
    worst
}

#[test]
fn short_arcs_at_r_0_3_form_at_ordinary_and_utm_coordinates() {
    // Item 9 of T4-U1 phase B (T4-I9 r01's L line): realized bends of 0.06°,
    // 0.1°, 0.5° and 5° at R = 0.3 m, in-plane and skew, at X = 0 and at
    // (5e6, 3.5e6, 0) with d on the 2^-30 m grid (bit-identical there). The
    // tip flexibility's entries are far below the dense solver's absolute
    // pivot guard (1e-12), which refused these arcs before the scaled
    // inversion; now each forms, K is bit-identical at both X, meets the
    // intended element to 1e-9 of max|K| and of √(K_ii K_jj) (P4, P4d) and
    // annihilates the rigid motions to 1e-11 (P1).
    let mut refused_unscaled = Vec::new();
    for arc in ARCS {
        let base = element([0.0, 0.0, 0.0], arc).expect(arc.label);
        let utm = element([5.0e6, 3.5e6, 0.0], arc).expect(arc.label);
        assert_eq!(utm.chord(), arc.d, "{}: d at X = 5e6", arc.label);
        let k = base.global_stiffness().expect(arc.label);
        let k_utm = utm.global_stiffness().expect(arc.label);
        for r in 0..12 {
            for c in 0..12 {
                assert_eq!(
                    k[r][c].to_bits(),
                    k_utm[r][c].to_bits(),
                    "{}: P3",
                    arc.label
                );
            }
        }
        let scale = arc.k.iter().flatten().fold(0.0_f64, |m, v| m.max(v.abs()));
        let (mut p4, mut p4d) = (0.0_f64, 0.0_f64);
        for r in 0..12 {
            for c in 0..12 {
                let difference = (k[r][c] - arc.k[r][c]).abs();
                p4 = p4.max(difference / scale);
                let pair = (arc.k[r][r] * arc.k[c][c]).abs().sqrt();
                if pair > 0.0 {
                    p4d = p4d.max(difference / pair);
                } else {
                    assert_eq!(difference, 0.0, "{}: [{r}][{c}]", arc.label);
                }
            }
        }
        let p1 = null_residual(&k, arc.d);
        eprintln!(
            "short arc {}: P4 {p4:.2e}, P4d {p4d:.2e}, P1 {p1:.2e}",
            arc.label
        );
        assert!(p4 <= 1e-9, "{}: P4 {p4:e}", arc.label);
        assert!(p4d <= 1e-9, "{}: P4d {p4d:e}", arc.label);
        assert!(p1 <= 1e-11, "{}: P1 {p1:e}", arc.label);
        let geometry = base.geometry().unwrap();
        let flexibility = base.flexibility_of(&geometry);
        match invert_unscaled(&flexibility) {
            Ok(unscaled) => {
                // Where the unscaled solve forms, the scaled one is bit-identical.
                let scaled = invert_symmetric6(&flexibility).unwrap();
                for r in 0..6 {
                    for c in 0..6 {
                        assert_eq!(
                            scaled[r][c].to_bits(),
                            unscaled[r][c].to_bits(),
                            "{}",
                            arc.label
                        );
                    }
                }
            }
            Err(_) => refused_unscaled.push(arc.label),
        }
    }
    // Precondition: the unscaled guard refused the short arcs (the test
    // discriminates).
    eprintln!("refused by the unscaled guard: {refused_unscaled:?}");
    for label in ["0.06deg-IP", "0.06deg-SK", "0.1deg-IP", "0.1deg-SK"] {
        assert!(
            refused_unscaled.contains(&label),
            "{label}: {refused_unscaled:?}"
        );
    }
}

#[test]
fn scaled_inversion_is_bit_identical_where_the_unscaled_one_forms() {
    // The power-of-two scaling is exact in every operation of the solve, so
    // ordinary elements keep their bits (no published number moves).
    let mut compared = 0;
    for degrees in [5.0_f64, 30.0, 90.0, 150.0, 179.0] {
        for radius in [0.3_f64, 1.5, 30.0] {
            let phi = degrees.to_radians();
            let length = 2.0 * radius * (0.5 * phi).sin();
            let xj = [length * 0.6, length * 0.8, 0.0];
            let e = CurvedBendMacroElement::new(
                FrameNode::new(0, [0.0; 3]).unwrap(),
                FrameNode::new(1, xj).unwrap(),
                radius,
                [0.0, 0.0, 1.0],
                SECTION.0,
                SECTION.1,
                SECTION.2,
                SECTION.3,
                SECTION.4,
                1.0,
                1.0,
            )
            .unwrap();
            let flexibility = e.flexibility_of(&e.geometry().unwrap());
            let Ok(unscaled) = invert_unscaled(&flexibility) else {
                continue;
            };
            compared += 1;
            let scaled = invert_symmetric6(&flexibility).unwrap();
            for r in 0..6 {
                for c in 0..6 {
                    assert_eq!(
                        scaled[r][c].to_bits(),
                        unscaled[r][c].to_bits(),
                        "{degrees} {radius}"
                    );
                }
            }
        }
    }
    assert!(compared >= 12, "{compared}");
}

