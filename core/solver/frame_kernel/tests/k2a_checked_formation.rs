/// Today's coefficients, operation for operation (FK `local_stiffness` at
/// 5ae22926e): axial, torsion, then 12, 6, 4, 2 for y, then for z.
fn unchecked_coefficients(p: &FrameProperties) -> [f64; 10] {
    let s = p.section;
    let (e, g, area, iy, iz, j) = (
        s.elastic_modulus,
        s.shear_modulus,
        s.area,
        s.second_moment_y,
        s.second_moment_z,
        s.torsion_constant,
    );
    let length = p.length;
    let length2 = length * length;
    let length3 = length2 * length;
    [
        e * area / length,
        g * j / length,
        12.0 * e * iy / length3,
        6.0 * e * iy / length2,
        4.0 * e * iy / length,
        2.0 * e * iy / length,
        12.0 * e * iz / length3,
        6.0 * e * iz / length2,
        4.0 * e * iz / length,
        2.0 * e * iz / length,
    ]
}
const AXIAL: usize = 0;
const TORSION: usize = 1;
const BY12: usize = 2;
const BY6: usize = 3;
const BY4: usize = 4;
const BY2: usize = 5;
const BZ12: usize = 6;

/// Today's matrix layout (FK `local_stiffness`, `set_symmetric`,
/// `add_bending_z`, `add_bending_y` and `add_terms` at 5ae22926e), without
/// the final finiteness check, from the unchecked coefficients.
fn unchecked_local(p: &FrameProperties) -> Matrix12 {
    let c = unchecked_coefficients(p);
    let mut k = [[0.0; ELEMENT_DOF]; ELEMENT_DOF];
    let sym = |k: &mut Matrix12, r: usize, col: usize, v: f64| {
        k[r][col] = v;
        k[col][r] = v;
    };
    sym(&mut k, UX, UX + DOF_PER_NODE, -c[AXIAL]);
    k[UX][UX] = c[AXIAL];
    k[UX + DOF_PER_NODE][UX + DOF_PER_NODE] = c[AXIAL];
    sym(&mut k, RX, RX + DOF_PER_NODE, -c[TORSION]);
    k[RX][RX] = c[TORSION];
    k[RX + DOF_PER_NODE][RX + DOF_PER_NODE] = c[TORSION];
    let add = |k: &mut Matrix12, idx: [usize; 4], t: [[f64; 4]; 4]| {
        for r in 0..4 {
            for col in 0..4 {
                k[idx[r]][idx[col]] += t[r][col];
            }
        }
    };
    let (z12, z6, z4, z2) = (c[6], c[7], c[8], c[9]);
    add(
        &mut k,
        [UY, RZ, UY + DOF_PER_NODE, RZ + DOF_PER_NODE],
        [
            [z12, z6, -z12, z6],
            [z6, z4, -z6, z2],
            [-z12, -z6, z12, -z6],
            [z6, z2, -z6, z4],
        ],
    );
    let (y12, y6, y4, y2) = (c[2], c[3], c[4], c[5]);
    add(
        &mut k,
        [UZ, RY, UZ + DOF_PER_NODE, RY + DOF_PER_NODE],
        [
            [y12, -y6, -y12, -y6],
            [-y6, y4, y6, y2],
            [-y12, y6, y12, y6],
            [-y6, y2, y6, y4],
        ],
    );
    k
}

fn bits(k: &Matrix12) -> Vec<u64> {
    k.iter().flatten().map(|v| v.to_bits()).collect()
}

/// The section as PP `derive_pipe_section` forms it
/// (`core/product_physics/src/lib.rs:8471-8475` at 5ae22926e).
fn product_section(e: f64, g: f64, od: f64, t: f64) -> FrameSection {
    let id = od - 2.0 * t;
    let area = PI * (od.powi(2) - id.powi(2)) / 4.0;
    let second_moment = PI * (od.powi(4) - id.powi(4)) / 64.0;
    FrameSection::new(
        e,
        g,
        area,
        second_moment,
        second_moment,
        2.0 * second_moment,
    )
    .unwrap()
}

fn member_properties(m: &RangeMember) -> FrameProperties {
    let section = product_section(
        f64::from_bits(m.e),
        f64::from_bits(m.g),
        f64::from_bits(m.od),
        f64::from_bits(m.t),
    );
    FrameProperties::new(section, f64::from_bits(m.length)).unwrap()
}

fn operands(o: &Operands) -> FrameProperties {
    let v = o.map(f64::from_bits);
    FrameProperties::new(
        FrameSection::new(v[0], v[1], v[2], v[3], v[4], v[5]).unwrap(),
        v[6],
    )
    .unwrap()
}

/// A member along global x from the origin, y reference along global y.
fn x_member(p: &FrameProperties) -> Result<FrameElement, FrameKernelError> {
    FrameElement::new(
        FrameNode::new(0, [0.0, 0.0, 0.0]).unwrap(),
        FrameNode::new(1, [p.length, 0.0, 0.0]).unwrap(),
        p.section,
        [0.0, 1.0, 0.0],
    )
}

fn range(name: &'static str) -> Result<Matrix12, FrameKernelError> {
    Err(FrameKernelError::NumericalRange { name })
}

/// 12EIy/L^3 formed with E scaled by 2^s (exact, all operands normal), then
/// scaled back (exact: the result is normal): the reference for the relative
/// error of the unchecked coefficient, accurate to a few ulps.
fn scaled_bend_y(p: &FrameProperties, k: f64, denominator_power: i32, s: i32) -> f64 {
    let sec = p.section;
    let e_scaled = sec.elastic_modulus * 2f64.powi(s);
    assert!(e_scaled.is_normal());
    let intermediate = k * e_scaled * sec.second_moment_y;
    assert!(intermediate.is_normal());
    let value = intermediate / p.length.powi(denominator_power) * 2f64.powi(-s);
    assert!(value.is_normal());
    value
}

fn relative_error(value: f64, reference: f64) -> f64 {
    ((value - reference) / reference).abs()
}

