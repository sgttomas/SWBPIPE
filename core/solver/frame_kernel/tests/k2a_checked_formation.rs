/// The global stiffness of a model from a given element matrix, springs
/// added after the element, as K-D5's adapter tests assemble it.
fn kd5_stiffness(model: &Kd5Model, element_matrix: &Matrix12) -> Vec<Vec<f64>> {
    let mut k = vec![vec![0.0; 12]; 12];
    let map = element_dof_map(0, 1);
    for r in 0..12 {
        for c in 0..12 {
            k[map[r]][map[c]] += element_matrix[r][c];
        }
    }
    for &(dof, value) in &model.springs {
        k[dof][dof] += value;
    }
    k
}

