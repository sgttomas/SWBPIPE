//! step 1; the K2a row of section 6; mutation 18 of section 7.3).
//!
//! `local_stiffness` forms every coefficient with the same binary64
//! operations as before, and checks every intermediate product and quotient.
//! A zero, subnormal or non-finite intermediate of nonzero finite operands is
//! `FrameKernelError::NumericalRange { name }`, naming the coefficient and the
//! intermediate. Every behavioural assertion on a refusal first shows the
//! silent or loud path on the unchecked formation (today's formula, computed
//! here operation for operation), so the paths are known to differ.
//!
//! Invented inputs only. The RF-RANGE members are R1's frozen references
//! (`tests/k2a/rf_range_models.rs`, generated by the run record
//! `k2a_models.py`); the section is formed as PP `derive_pipe_section` forms
//! it. The K-D5 interaction uses V1's F122 and F345 models as K-D5's adapter
//! tests carry them (`nonlinear_integration/src/structural_adapter/kd5_models.rs`).
